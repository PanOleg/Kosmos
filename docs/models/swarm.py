# Рій (SWARM): крихітний колючий дрон, гострі «щелепи» спереду, шипи навсібіч.
# Дрон: центр корпусу в початку координат.
hull, glow = bmesh.new(), bmesh.new()
blob(hull, DARK, (0, 0, -0.02), (0.2, 0.16, 0.26))
spike(hull, MID, (0, 0.06, -0.02), (0, 0.24, -0.12), 0.08, 0.08)
def side(sx):
    spike(hull, PALE, (0.05*sx, -0.02, 0.08), (0.07*sx, -0.06, 0.24), 0.04, 0.04)
    spike(hull, MID, (0.08*sx, 0.02, 0.0), (0.26*sx, 0.06, -0.06), 0.05, 0.03)
    spike(hull, RED, (0.06*sx, 0.03, -0.08), (0.18*sx, 0.1, -0.2), 0.03, 0.03)
mirror(side)
box(glow, WHITE, (0, 0.02, 0.12), (0.08, 0.05, 0.03))
build('Swarm', hull, glow, offset_x=10.0)
