# Ліс, Панцир → Велетенський олень: кора-броня на боках, мохова спина зі світними плямами,
# величезні світні роги, ззаду на крупі — бурштиновий світний міхур (слабке місце).
# Стоїть на підлозі; тулуб вище 1.2 (стегно), ноги нижче.
hull, glow = bmesh.new(), bmesh.new()
def side(sx):
    # Передня нога.
    frustum(hull, F_BARK, (0.4*sx, 1.36, 0.6), (0.42*sx, 0.72, 0.66), 0.28, 0.32, 0.18, 0.2)
    box(hull, F_BARKL, (0.42*sx, 0.72, 0.7), (0.2, 0.2, 0.14))
    frustum(hull, F_BARKL, (0.42*sx, 0.72, 0.66), (0.42*sx, 0.14, 0.6), 0.18, 0.2, 0.14, 0.16)
    box(hull, F_BLACK, (0.42*sx, 0.07, 0.63), (0.24, 0.14, 0.3))
    # Задня нога: масивне стегно, скакальний суглоб назад.
    frustum(hull, F_BARK, (0.4*sx, 1.4, -0.6), (0.43*sx, 0.74, -0.8), 0.3, 0.42, 0.18, 0.2)
    box(hull, F_BARKL, (0.43*sx, 0.74, -0.84), (0.2, 0.2, 0.14))
    frustum(hull, F_BARKL, (0.43*sx, 0.74, -0.8), (0.43*sx, 0.14, -0.66), 0.18, 0.2, 0.14, 0.16)
    box(hull, F_BLACK, (0.43*sx, 0.07, -0.63), (0.24, 0.14, 0.3))
    # Кора-броня на боках зі світними рунами.
    box(hull, F_BARK, (0.6*sx, 1.72, 0.0), (0.12, 0.62, 1.4))
    for z in (0.42, -0.42):
        box(hull, F_BARKL, (0.68*sx, 1.74, z), (0.08, 0.48, 0.46))
        box(glow, G_LIME, (0.725*sx, 1.74, z), (0.02, 0.32, 0.07))
        box(glow, G_LIME, (0.725*sx, 1.8, z), (0.02, 0.07, 0.26))
    # Плечова пластина.
    box(hull, F_MOSS, (0.5*sx, 2.06, 0.62), (0.3, 0.12, 0.5), rz=-0.35*sx)
    # Плями на спині.
    for k, z in enumerate((0.42, 0.06, -0.3, -0.64)):
        box(glow, G_CYAN, ((0.3 - 0.02*k)*sx, 2.105, z), (0.16, 0.03, 0.16), ry=0.785)
    # Вухо й око.
    spike(hull, F_BARKL, (0.16*sx, 2.44, 1.2), (0.44*sx, 2.52, 1.08), 0.14, 0.06)
    box(glow, G_AMBER, (0.175*sx, 2.42, 1.42), (0.02, 0.07, 0.1))
    # Ріг: головна гілка з трьох ланок і п'ять відростків.
    a0, a1, a2, a3 = (0.12*sx, 2.5, 1.24), (0.42*sx, 2.78, 1.0), (0.72*sx, 2.94, 0.62), (0.95*sx, 3.0, 0.2)
    frustum(glow, G_CYAN, a0, a1, 0.15, 0.15, 0.14, 0.14)
    frustum(glow, G_CYAN, a1, a2, 0.14, 0.14, 0.12, 0.12)
    frustum(glow, G_CYAN, a2, a3, 0.12, 0.12, 0.09, 0.09)
    spike(glow, G_VIOLET, a3, (1.15*sx, 3.06, -0.12), 0.09, 0.09)
    spike(glow, G_VIOLET, L3(a0, a1, 0.5), (0.26*sx, 2.76, 1.64), 0.11, 0.11)
    spike(glow, G_VIOLET, a1, (0.64*sx, 2.98, 1.48), 0.13, 0.13)
    spike(glow, G_VIOLET, L3(a1, a2, 0.55), (0.92*sx, 3.04, 1.24), 0.12, 0.12)
    spike(glow, G_VIOLET, a2, (1.16*sx, 3.04, 0.98), 0.12, 0.12)
    spike(glow, G_VIOLET, L3(a2, a3, 0.55), (1.22*sx, 3.06, 0.66), 0.1, 0.1)
    spike(glow, G_VIOLET, a2, (0.5*sx, 3.08, 0.34), 0.1, 0.1)
mirror(side)
# Тулуб.
box(hull, F_BARK, (0, 1.3, 0), (0.8, 0.2, 1.5))
box(hull, F_TEALD, (0, 1.68, 0), (1.08, 0.66, 1.9))
frustum(hull, F_TEALD, (0, 1.7, 0.9), (0, 1.74, 1.12), 0.9, 0.6, 0.6, 0.44)
box(hull, F_MOSS, (0, 2.04, -0.08), (0.94, 0.1, 1.66))
blob(hull, F_MOSS, (0, 2.06, 0.5), (0.7, 0.4, 0.7), sub=2)
for z in (0.0, -0.36, -0.7):
    spike(hull, F_BARK, (0, 2.09, z), (0, 2.26, z - 0.14), 0.12, 0.26)
# Шия, грива, голова.
frustum(hull, F_BARK, (0, 1.8, 0.85), (0, 2.3, 1.2), 0.46, 0.5, 0.32, 0.36)
frustum(hull, F_PALE, (0, 1.72, 1.02), (0, 1.38, 1.12), 0.42, 0.3, 0.18, 0.12)
frustum(glow, G_CYAN, (0, 2.06, 0.8), (0, 2.5, 1.1), 0.1, 0.03)
box(hull, F_BARK, (0, 2.36, 1.34), (0.34, 0.3, 0.44))
frustum(hull, F_BARKL, (0, 2.33, 1.54), (0, 2.25, 1.8), 0.26, 0.22, 0.18, 0.14)
box(hull, F_BLACK, (0, 2.24, 1.81), (0.16, 0.1, 0.04))
box(glow, G_CYAN, (0, 2.52, 1.36), (0.1, 0.03, 0.2), ry=0.785)
# Хвостик і слабке місце ззаду.
frustum(hull, F_PALE, (0, 1.98, -0.93), (0, 2.14, -1.1), 0.2, 0.12, 0.1, 0.06)
cyl(hull, F_BLACK, (0, 1.62, -0.95), (0, 1.62, -1.0), 0.36, n=12)
blob(glow, G_AMBER, (0, 1.62, -1.0), (0.56, 0.56, 0.34), sub=2)
box(glow, G_AMBER, (0, 2.1, -0.88), (0.3, 0.03, 0.1))
build('FShell', hull, glow, offset_x=-3.0)
