# Ліс, Панцир → Велетенський олень: струнке оленяче тіло (груди, вузький стан, круп),
# довга шия, голова з мордою вперед, широкі гіллясті роги (кістяні балки, світні відростки),
# мохова спина зі світними плямами, ззаду на крупі — бурштиновий світний міхур (слабке місце).
# Стоїть на підлозі; тулуб вище 1.2 (стегно), ноги нижче, розставлені по кутах.
hull, glow = bmesh.new(), bmesh.new()
# Перетини тулуба вздовж Z: (z, центр y, ширина, висота).
SEC = ((-1.0, 1.74, 0.6, 0.6), (-0.55, 1.75, 0.86, 0.76), (-0.05, 1.8, 0.56, 0.54),
       (0.5, 1.75, 0.9, 0.84), (0.94, 1.84, 0.56, 0.6))
def top(z):
    """Висота спини над точкою z."""
    for a, b in zip(SEC, SEC[1:]):
        if a[0] <= z <= b[0]:
            t = (z - a[0]) / (b[0] - a[0])
            return a[1] + a[3] / 2 + (b[1] + b[3] / 2 - a[1] - a[3] / 2) * t
    return 2.1
for a, b in zip(SEC, SEC[1:]):
    frustum(hull, F_TEALD, (0, a[1], a[0]), (0, b[1], b[0]), a[2], a[3], b[2], b[3])
    # Мохова смуга вздовж хребта.
    frustum(hull, F_MOSS, (0, a[1] + a[3] / 2, a[0]), (0, b[1] + b[3] / 2, b[0]), a[2] * 0.62, 0.07, b[2] * 0.62, 0.07)
def side(sx):
    # Передня нога: плече, зап'ясток, світла гомілка, копито.
    frustum(hull, F_BARK, (0.32*sx, 1.56, 0.6), (0.46*sx, 0.74, 0.72), 0.26, 0.36, 0.16, 0.18)
    frustum(hull, F_PALE, (0.46*sx, 0.74, 0.72), (0.54*sx, 0.14, 0.68), 0.15, 0.17, 0.12, 0.14)
    box(hull, F_BLACK, (0.54*sx, 0.07, 0.71), (0.2, 0.14, 0.28))
    # Задня нога: масивне стегно, скакальний суглоб назад.
    frustum(hull, F_BARK, (0.32*sx, 1.6, -0.56), (0.46*sx, 0.76, -0.86), 0.28, 0.46, 0.16, 0.2)
    frustum(hull, F_PALE, (0.46*sx, 0.76, -0.86), (0.54*sx, 0.14, -0.72), 0.15, 0.18, 0.12, 0.14)
    box(hull, F_BLACK, (0.54*sx, 0.07, -0.69), (0.2, 0.14, 0.28))
    # Кора-броня на плечі й стегні зі світними рунами.
    for z in (0.5, -0.55):
        box(hull, F_BARK, (0.44*sx, 1.84, z), (0.1, 0.44, 0.46))
        box(glow, G_LIME, (0.495*sx, 1.84, z), (0.02, 0.3, 0.07))
        box(glow, G_LIME, (0.495*sx, 1.9, z), (0.02, 0.07, 0.24))
    # Плями на спині (як у оленяти), два ряди.
    for k, z in enumerate((0.62, 0.3, -0.05, -0.4, -0.72)):
        x = (0.2, 0.26, 0.15, 0.25, 0.2)[k]
        box(glow, G_CYAN, (x*sx, top(z) + 0.045, z), (0.13, 0.03, 0.13), ry=0.785)
    # Вухо й око.
    spike(hull, F_BARKL, (0.15*sx, 2.7, 1.24), (0.42*sx, 2.76, 1.1), 0.14, 0.06)
    box(glow, G_AMBER, (0.165*sx, 2.66, 1.46), (0.02, 0.07, 0.1))
    # Ріг: кістяна балка розходиться від голови вбік-назад (згори — літера V); довгі відростки
    # гілкуються навскіс уперед-назовні й один усередину, на кінці вилка; кінчики світяться.
    a0, a1, a2, a3 = (0.11*sx, 2.74, 1.28), (0.42*sx, 3.02, 1.0), (0.84*sx, 3.16, 0.5), (1.0*sx, 3.2, -0.12)
    frustum(hull, F_CREAM, a0, a1, 0.16, 0.16, 0.15, 0.15)
    frustum(hull, F_CREAM, a1, a2, 0.15, 0.15, 0.13, 0.13)
    frustum(hull, F_CREAM, a2, a3, 0.13, 0.13, 0.11, 0.11)
    tipped(hull, glow, F_CREAM, G_CYAN, L3(a0, a1, 0.3), (0.3*sx, 2.92, 1.86), 0.11, 0.11, f=0.62)
    tipped(hull, glow, F_CREAM, G_CYAN, a1, (0.98*sx, 3.24, 1.46), 0.13, 0.13, f=0.62)
    tipped(hull, glow, F_CREAM, G_VIOLET, a2, (1.32*sx, 3.3, 0.9), 0.12, 0.12, f=0.62)
    tipped(hull, glow, F_CREAM, G_CYAN, L3(a1, a2, 0.7), (0.4*sx, 3.5, 0.3), 0.11, 0.11, f=0.62)
    tipped(hull, glow, F_CREAM, G_VIOLET, a3, (1.33*sx, 3.3, -0.3), 0.11, 0.11, f=0.62)
    tipped(hull, glow, F_CREAM, G_CYAN, a3, (0.84*sx, 3.32, -0.72), 0.11, 0.11, f=0.62)
mirror(side)
# Шия з гривою, світле горло, голова з мордою вперед.
frustum(hull, F_TEALD, (0, 1.92, 0.8), (0, 2.56, 1.24), 0.42, 0.5, 0.3, 0.34)
frustum(hull, F_PALE, (0, 1.76, 1.02), (0, 2.3, 1.36), 0.3, 0.16, 0.2, 0.1)
frustum(glow, G_CYAN, (0, 2.2, 0.76), (0, 2.72, 1.12), 0.09, 0.03)
box(hull, F_BARK, (0, 2.62, 1.38), (0.32, 0.3, 0.42))
frustum(hull, F_BARKL, (0, 2.6, 1.57), (0, 2.5, 1.86), 0.25, 0.22, 0.16, 0.13)
box(hull, F_BLACK, (0, 2.5, 1.87), (0.14, 0.1, 0.04))
box(glow, G_CYAN, (0, 2.78, 1.42), (0.1, 0.03, 0.18), ry=0.785)
# Короткий хвостик і слабке місце ззаду.
frustum(hull, F_PALE, (0, 2.02, -0.98), (0, 2.22, -1.16), 0.22, 0.12, 0.1, 0.06)
cyl(hull, F_BLACK, (0, 1.72, -0.99), (0, 1.72, -1.05), 0.36, n=12)
blob(glow, G_AMBER, (0, 1.72, -1.05), (0.56, 0.56, 0.34), sub=2)
box(glow, G_AMBER, (0, 2.09, -0.86), (0.3, 0.03, 0.1))
build('FShell', hull, glow, offset_x=-3.0)
