# Ліс, Снайпер → Колібрі: маленьке тіло, дуже довгий дзьоб-голка, гострі відведені назад крила
# зі світною кромкою, хвіст-віяло зі світними кінчиками. Дрон: центр корпусу в початку координат.
hull, glow = bmesh.new(), bmesh.new()
frustum(hull, F_TEAL, (0, 0, -0.12), (0, 0.02, 0.28), 0.16, 0.15, 0.22, 0.19)
frustum(hull, F_TEALD, (0, 0, -0.12), (0, -0.04, -0.36), 0.14, 0.12, 0.1, 0.06)
frustum(glow, G_MAGENTA, (0, 0.085, -0.1), (0, 0.12, 0.24), 0.07, 0.02, 0.1, 0.02)
blob(hull, F_TEAL, (0, 0.05, 0.38), (0.2, 0.18, 0.2))
box(glow, G_MAGENTA, (0, 0.135, 0.37), (0.09, 0.03, 0.1))
cyl(hull, F_BLACK, (0, 0.03, 0.44), (0, 0.01, 1.4), 0.026, 0.012, n=5)
box(glow, G_CYAN, (0, 0.01, 1.43), (0.04, 0.04, 0.1))
for a in (-0.8, -0.4, 0.0, 0.4, 0.8):
    tip = (0.34 * math.sin(a), -0.16, -0.34 - 0.3 * math.cos(a))
    tipped(hull, glow, F_INDIGO, G_LIME, (0, -0.04, -0.33), tip, 0.1, 0.02, f=0.6)
def side(sx):
    frustum(hull, F_INDIGO, (0.09*sx, 0.08, 0.16), (0.4*sx, 0.14, 0.02), 0.2, 0.02, 0.17, 0.02)
    spike(hull, F_INDIGO, (0.4*sx, 0.14, 0.02), (0.64*sx, 0.18, -0.32), 0.17, 0.02)
    spike(hull, F_TEALD, (0.14*sx, 0.07, 0.04), (0.46*sx, 0.1, -0.3), 0.14, 0.015)
    frustum(glow, G_CYAN, (0.12*sx, 0.1, 0.24), (0.42*sx, 0.16, 0.1), 0.04, 0.02)
    spike(glow, G_CYAN, (0.42*sx, 0.16, 0.1), (0.65*sx, 0.19, -0.33), 0.05, 0.02)
    box(glow, G_AMBER, (0.085*sx, 0.07, 0.42), (0.04, 0.05, 0.05))
    spike(hull, F_BLACK, (0.05*sx, -0.07, 0.1), (0.07*sx, -0.2, 0.16), 0.025, 0.025)
mirror(side)
build('FSniper', hull, glow, offset_x=8.0)
