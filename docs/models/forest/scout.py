# Ліс, Скаут → Лис-дух: чотири лапи, великі вуха, пишний хвіст зі світним кінчиком,
# блакитна смуга вздовж хребта. Стоїть на підлозі, дивиться на +Z. Стегно ~0.55.
hull, glow = bmesh.new(), bmesh.new()
frustum(hull, F_TEAL, (0, 0.68, -0.42), (0, 0.72, 0.3), 0.26, 0.28, 0.32, 0.34)
box(hull, F_PALE, (0, 0.66, 0.3), (0.22, 0.22, 0.1))
frustum(glow, G_CYAN, (0, 0.825, -0.4), (0, 0.895, 0.28), 0.08, 0.03)
frustum(hull, F_TEAL, (0, 0.76, 0.26), (0, 0.95, 0.5), 0.22, 0.24, 0.18, 0.2)
box(hull, F_TEAL, (0, 0.98, 0.6), (0.26, 0.2, 0.24))
frustum(hull, F_PALE, (0, 0.94, 0.7), (0, 0.9, 0.96), 0.16, 0.12, 0.07, 0.06)
box(hull, F_BLACK, (0, 0.9, 0.975), (0.06, 0.05, 0.04))
# Хвіст: тонка основа, пишна середина, світний кінчик (усе вище стегна).
frustum(hull, F_TEAL, (0, 0.74, -0.4), (0, 0.9, -0.66), 0.12, 0.12, 0.28, 0.26)
frustum(hull, F_INDIGO, (0, 0.9, -0.66), (0, 0.88, -0.9), 0.28, 0.26, 0.2, 0.19)
spike(glow, G_MAGENTA, (0, 0.88, -0.9), (0, 0.76, -1.12), 0.2, 0.19)
def side(sx):
    spike(hull, F_INDIGO, (0.09*sx, 1.06, 0.56), (0.15*sx, 1.38, 0.5), 0.12, 0.06)
    spike(glow, G_MAGENTA, (0.09*sx, 1.07, 0.59), (0.14*sx, 1.3, 0.53), 0.06, 0.02)
    box(glow, G_AMBER, (0.1*sx, 1.01, 0.725), (0.06, 0.04, 0.02))
    # Передня лапа з темною «шкарпеткою».
    frustum(hull, F_TEALD, (0.15*sx, 0.62, 0.2), (0.16*sx, 0.32, 0.28), 0.11, 0.13, 0.08, 0.09)
    frustum(hull, F_NIGHT, (0.16*sx, 0.32, 0.28), (0.16*sx, 0.05, 0.25), 0.08, 0.09, 0.07, 0.08)
    box(hull, F_BLACK, (0.16*sx, 0.03, 0.29), (0.1, 0.06, 0.17))
    # Задня: масивне стегно, коліно назад.
    frustum(hull, F_TEALD, (0.15*sx, 0.66, -0.32), (0.17*sx, 0.34, -0.5), 0.13, 0.2, 0.09, 0.1)
    frustum(hull, F_NIGHT, (0.17*sx, 0.34, -0.5), (0.17*sx, 0.05, -0.39), 0.08, 0.09, 0.07, 0.08)
    box(hull, F_BLACK, (0.17*sx, 0.03, -0.35), (0.1, 0.06, 0.17))
    # Світні плями на боках (вище стегна).
    box(glow, G_CYAN, (0.15*sx, 0.76, -0.22), (0.03, 0.09, 0.1))
    box(glow, G_CYAN, (0.165*sx, 0.78, 0.06), (0.03, 0.07, 0.08))
mirror(side)
build('FScout', hull, glow, offset_x=0.0)
