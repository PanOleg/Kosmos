# Ліс, Турель → Гриб-турель: товста ніжка з корінням, широкий капелюшок зі світними плямами,
# спорова труба-«лійка» на +Z, ззаду на відростку — світний споровий міхур (слабке місце).
hull, glow = bmesh.new(), bmesh.new()
for sx, sz in ((1, 1), (-1, 1), (1, -1), (-1, -1)):
    frustum(hull, F_BARK, (0.2*sx, 0.16, 0.2*sz), (0.52*sx, 0.03, 0.5*sz), 0.16, 0.14, 0.08, 0.06)
cyl(hull, F_CREAM, (0, 0, 0), (0, 0.62, 0), 0.34, 0.26, n=8)
cyl(hull, F_INDIGO, (0, 0.6, 0), (0, 0.72, 0), 0.64, 0.58, n=10)
cyl(hull, F_PLUM, (0, 0.72, 0), (0, 1.08, 0), 0.58, 0.18, n=10)
# Плями на капелюшку: два кільця й верхівка.
SL = 0.73
for k in range(5):
    t = math.radians(36 + 72 * k)
    box(glow, G_CYAN if k % 2 else G_MAGENTA, (0.43 * math.sin(t), 0.845, 0.43 * math.cos(t)), (0.22, 0.05, 0.2), rx=SL, ry=t)
for k in range(3):
    t = math.radians(120 * k)
    box(glow, G_CYAN, (0.25 * math.sin(t), 1.005, 0.25 * math.cos(t)), (0.15, 0.05, 0.14), rx=SL, ry=t)
box(glow, G_LIME, (0, 1.085, 0), (0.2, 0.04, 0.2), ry=0.785)
# Спорова труба.
cyl(hull, F_CREAM, (0, 0.38, 0.2), (0, 0.44, 0.92), 0.1, 0.18, n=8)
cyl(hull, F_PLUM, (0, 0.435, 0.84), (0, 0.445, 0.98), 0.2, 0.24, n=8)
cyl(glow, G_LIME, (0, 0.445, 0.975), (0, 0.445, 0.995), 0.19, n=8)
# Слабке місце ззаду.
frustum(hull, F_BARK, (0, 0.2, -0.25), (0, 0.44, -0.74), 0.22, 0.22, 0.18, 0.18)
box(hull, F_BLACK, (0, 0.46, -0.73), (0.46, 0.36, 0.1))
blob(glow, G_AMBER, (0, 0.48, -0.82), (0.42, 0.42, 0.36))
# Грибочки-малюки спереду.
def side(sx):
    cyl(hull, F_CREAM, (0.5*sx, 0, 0.66), (0.5*sx, 0.2, 0.66), 0.05, n=5)
    spike(hull, F_PLUM, (0.5*sx, 0.2, 0.66), (0.5*sx, 0.34, 0.66), 0.24, 0.24)
    spike(glow, G_MAGENTA, (0.5*sx, 0.285, 0.66), (0.5*sx, 0.36, 0.66), 0.11, 0.11)
mirror(side)
build('FTurret', hull, glow, offset_x=-10.5)
