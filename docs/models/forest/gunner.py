# Ліс, Стрілець → Дикобраз: сидить стовпчиком на задніх лапах, віяло голок на спині
# зі світними кінчиками, над головою — «ствол» із жмутка голок, спрямований на +Z. Стегно ~0.42.
hull, glow = bmesh.new(), bmesh.new()
def side(sx):
    frustum(hull, F_BARK, (0.2*sx, 0.5, -0.02), (0.22*sx, 0.08, 0.06), 0.2, 0.22, 0.14, 0.15)
    box(hull, F_BLACK, (0.22*sx, 0.04, 0.14), (0.16, 0.08, 0.32))
    frustum(hull, F_BARK, (0.27*sx, 0.9, 0.1), (0.2*sx, 0.74, 0.34), 0.09, 0.09)
    box(glow, G_MAGENTA, (0.12*sx, 1.13, 0.425), (0.07, 0.06, 0.02))
    box(hull, F_BARKL, (0.17*sx, 1.24, 0.2), (0.08, 0.08, 0.06))
mirror(side)
frustum(hull, F_BARK, (0, 0.42, -0.08), (0, 1.0, 0.08), 0.62, 0.56, 0.46, 0.42)
box(hull, F_PALE, (0, 0.7, 0.245), (0.3, 0.4, 0.05), rx=-0.13)
box(hull, F_BARK, (0, 1.08, 0.26), (0.34, 0.28, 0.32))
frustum(hull, F_BARKL, (0, 1.04, 0.4), (0, 0.99, 0.62), 0.2, 0.16, 0.1, 0.08)
box(hull, F_BLACK, (0, 0.99, 0.63), (0.08, 0.06, 0.04))
# «Ствол»: темний жмуток над головою і три голки зі світними кінчиками.
cyl(hull, F_NIGHT, (0, 1.3, -0.05), (0, 1.33, 0.5), 0.11, 0.085, n=6)
for dx, dy in ((0, 0.04), (-0.045, -0.03), (0.045, -0.03)):
    tipped(hull, glow, F_CREAM, G_AMBER, (dx, 1.33 + dy, 0.45), (dx, 1.33 + dy, 0.8), 0.05, 0.05, f=0.5)
# Голки на спині: три ряди віялом.
for y, n, L in ((0.5, 4, 0.5), (0.78, 5, 0.6), (1.02, 3, 0.52)):
    for k in range(n):
        a = (k - (n - 1) / 2) * 0.55
        bx, bz = 0.22 * math.sin(a), -0.12 - 0.14 * math.cos(a)
        tip = (bx + L * math.sin(a) * 0.62, y + L * 0.72, bz - L * 0.42 * math.cos(a))
        tipped(hull, glow, F_INDIGO, G_AMBER if (k + n) % 2 else G_MAGENTA, (bx, y, bz), tip, 0.13, 0.13, f=0.5)
build('FGunner', hull, glow, offset_x=2.0)
