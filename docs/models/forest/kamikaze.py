# Ліс, Камікадзе → Світляк: товстий жук із величезним світним черевцем, темні груди й голова,
# розкриті надкрила, фіолетові крильця. Дрон: центр у початку координат.
hull, glow = bmesh.new(), bmesh.new()
blob(glow, G_LIME, (0, -0.02, -0.2), (0.46, 0.4, 0.6), sub=2)
blob(glow, G_AMBER, (0, -0.04, -0.42), (0.28, 0.26, 0.2))
box(hull, F_BLACK, (0, 0.15, -0.08), (0.3, 0.06, 0.04))
box(hull, F_BLACK, (0, 0.15, -0.3), (0.3, 0.06, 0.04))
blob(hull, F_INDIGO, (0, 0.03, 0.2), (0.46, 0.34, 0.42))
box(hull, F_PLUM, (0, 0.17, 0.2), (0.26, 0.05, 0.22))
box(hull, F_BLACK, (0, 0.0, 0.44), (0.24, 0.16, 0.14))
def side(sx):
    spike(hull, F_PLUM, (0.2*sx, 0.14, 0.1), (0.6*sx, 0.22, -0.32), 0.26, 0.04)
    spike(glow, G_VIOLET, (0.22*sx, 0.09, -0.04), (0.52*sx, 0.11, -0.5), 0.16, 0.015)
    for z in (0.3, 0.16, 0.02):
        frustum(hull, F_BLACK, (0.18*sx, -0.08, z), (0.34*sx, -0.2, z + 0.05), 0.04, 0.04)
    spike(hull, F_BLACK, (0.07*sx, 0.06, 0.5), (0.2*sx, 0.14, 0.66), 0.025, 0.025)
    box(glow, G_MAGENTA, (0.11*sx, 0.03, 0.5), (0.06, 0.07, 0.06))
mirror(side)
build('FKamikaze', hull, glow, offset_x=6.0)
