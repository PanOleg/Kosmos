# Ліс, Оса → Сова: кругла голова з великими світними очима, широкі крила зі світною
# передньою кромкою та плямами, хвіст-віяло. Дрон: центр корпусу в початку координат.
hull, glow = bmesh.new(), bmesh.new()
frustum(hull, F_BARK, (0, 0, -0.28), (0, 0.02, 0.2), 0.2, 0.14, 0.28, 0.2)
blob(hull, F_BARKL, (0, 0.03, 0.36), (0.38, 0.24, 0.3))
spike(hull, F_CREAM, (0, 0.0, 0.48), (0, -0.07, 0.6), 0.07, 0.07)
frustum(hull, F_BARK, (0, 0, -0.28), (0, 0, -0.5), 0.16, 0.03, 0.36, 0.02)
box(glow, G_VIOLET, (0, 0.012, -0.46), (0.3, 0.02, 0.05))
def side(sx):
    spike(hull, F_INDIGO, (0.12*sx, 0.1, 0.34), (0.21*sx, 0.17, 0.24), 0.07, 0.04)
    box(glow, G_AMBER, (0.085*sx, 0.105, 0.44), (0.1, 0.05, 0.09), rx=0.5)
    frustum(hull, F_BARK, (0.1*sx, 0.04, 0.0), (0.5*sx, 0.1, -0.02), 0.42, 0.03, 0.38, 0.03)
    frustum(hull, F_INDIGO, (0.5*sx, 0.1, -0.02), (0.84*sx, 0.06, -0.12), 0.38, 0.03, 0.18, 0.02)
    for k in range(3):
        spike(hull, F_PALE, (0.8*sx, 0.06, -0.06 - k*0.07), (0.98*sx, 0.04, -0.14 - k*0.1), 0.02, 0.06)
    frustum(glow, G_CYAN, (0.12*sx, 0.065, 0.19), (0.5*sx, 0.125, 0.16), 0.05, 0.02)
    frustum(glow, G_CYAN, (0.5*sx, 0.125, 0.16), (0.86*sx, 0.08, -0.05), 0.05, 0.02)
    box(glow, G_VIOLET, (0.32*sx, 0.095, -0.06), (0.14, 0.02, 0.12), rz=0.15*sx)
mirror(side)
build('FWasp', hull, glow, offset_x=4.0)
