# Ліс, Ремонтник → Білка-цілителька: стоїть стовпчиком, підняла над головою світну зелену кулю,
# вуха з китицями, величезний пишний хвіст здіймається за спиною літерою S (кінчик загнутий назад)
# зі світними кільцями й кінчиком — згори він головна прикмета. Хвіст і черевце вище стегна 0.38.
hull, glow = bmesh.new(), bmesh.new()
def legs(sx):
    frustum(hull, F_BARK, (0.14*sx, 0.46, -0.02), (0.16*sx, 0.08, 0.06), 0.16, 0.2, 0.11, 0.12)
    box(hull, F_BARKL, (0.16*sx, 0.04, 0.14), (0.12, 0.08, 0.34))
    # Вухо з довгою світною китицею.
    tipped(hull, glow, F_BARK, G_AMBER, (0.1*sx, 1.14, 0.06), (0.19*sx, 1.42, -0.02), 0.1, 0.06, f=0.5)
    box(glow, G_AMBER, (0.14*sx, 1.08, 0.2), (0.03, 0.06, 0.06))
    # Лапка, піднята до кулі.
    frustum(hull, F_BARKL, (0.2*sx, 0.86, 0.08), (0.11*sx, 1.4, 0.3), 0.1, 0.1, 0.07, 0.07)
mirror(legs)
frustum(hull, F_BARK, (0, 0.4, -0.02), (0, 0.94, 0.06), 0.42, 0.38, 0.3, 0.26)
box(hull, F_PALE, (0, 0.68, 0.2), (0.22, 0.4, 0.05), rx=-0.13)
blob(hull, F_BARKL, (0, 1.05, 0.1), (0.32, 0.28, 0.32))
frustum(hull, F_PALE, (0, 1.02, 0.2), (0, 0.99, 0.38), 0.15, 0.13, 0.07, 0.06)
box(hull, F_BLACK, (0, 0.99, 0.39), (0.06, 0.05, 0.03))
# Цілюща куля над головою.
blob(glow, G_LIME, (0, 1.47, 0.3), (0.25, 0.25, 0.25))
# Хвіст літерою S із трьох пухнастих «клубків»: назад, угору, до потилиці (світлий завиток),
# кінчик — назад; між клубками світні кільця.
frustum(hull, F_BARKL, (0, 0.52, -0.16), (0, 0.66, -0.44), 0.16, 0.16, 0.3, 0.26)
blob(hull, F_BARKL, (0, 0.74, -0.52), (0.42, 0.44, 0.4))
blob(hull, F_BARKL, (0, 1.08, -0.62), (0.54, 0.5, 0.46))
blob(hull, F_CREAM, (0, 1.38, -0.46), (0.46, 0.4, 0.42))
spike(glow, G_CYAN, (0, 1.46, -0.6), (0, 1.4, -0.9), 0.2, 0.16)
blob(glow, G_VIOLET, (0, 0.91, -0.59), (0.47, 0.09, 0.42))
blob(glow, G_VIOLET, (0, 1.25, -0.55), (0.47, 0.09, 0.42))
build('FRepairer', hull, glow, offset_x=-8.0)
