# Ліс, Ремонтник → Білка-цілителька: стоїть стовпчиком, тримає в лапках світну зелену кулю,
# пишний хвіст дугою за спиною зі світним кінчиком і кільцями (хвіст вище стегна). Стегно ~0.42.
hull, glow = bmesh.new(), bmesh.new()
def legs(sx):
    frustum(hull, F_BARK, (0.14*sx, 0.46, -0.04), (0.16*sx, 0.08, 0.04), 0.17, 0.22, 0.11, 0.12)
    box(hull, F_BARKL, (0.16*sx, 0.04, 0.12), (0.12, 0.08, 0.34))
    tipped(hull, glow, F_BARK, G_AMBER, (0.1*sx, 1.24, 0.06), (0.15*sx, 1.44, 0.02), 0.09, 0.05, f=0.6)
    box(glow, G_AMBER, (0.13*sx, 1.17, 0.2), (0.03, 0.06, 0.06))
    box(hull, F_PALE, (0.09*sx, 1.08, 0.22), (0.1, 0.1, 0.1))
    frustum(hull, F_BARK, (0.2*sx, 0.9, 0.08), (0.1*sx, 0.74, 0.36), 0.08, 0.08)
mirror(legs)
frustum(hull, F_BARKL, (0, 0.4, -0.04), (0, 1.0, 0.06), 0.44, 0.4, 0.3, 0.26)
box(hull, F_PALE, (0, 0.7, 0.19), (0.22, 0.42, 0.05), rx=-0.13)
blob(hull, F_BARKL, (0, 1.14, 0.1), (0.3, 0.27, 0.3))
frustum(hull, F_PALE, (0, 1.1, 0.2), (0, 1.07, 0.38), 0.15, 0.13, 0.07, 0.06)
box(hull, F_BLACK, (0, 1.07, 0.39), (0.06, 0.05, 0.03))
blob(glow, G_LIME, (0, 0.72, 0.44), (0.22, 0.22, 0.22))
# Хвіст.
p0, p1, p2, p3 = (0, 0.5, -0.2), (0, 0.68, -0.46), (0, 1.08, -0.42), (0, 1.36, -0.54)
frustum(hull, F_BARK, p0, p1, 0.14, 0.14, 0.28, 0.24)
frustum(hull, F_BARKL, p1, p2, 0.28, 0.24, 0.32, 0.26)
frustum(hull, F_BARK, p2, p3, 0.32, 0.26, 0.26, 0.22)
spike(glow, G_CYAN, p3, (0, 1.26, -0.8), 0.26, 0.22)
frustum(glow, G_VIOLET, L3(p1, p2, 0.4), L3(p1, p2, 0.56), 0.31, 0.27)
frustum(glow, G_VIOLET, L3(p2, p3, 0.25), L3(p2, p3, 0.5), 0.33, 0.27, 0.31, 0.25)
build('FRepairer', hull, glow, offset_x=-8.0)
