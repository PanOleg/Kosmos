# Ліс, Павук → Лісовий павук: кругле черевце зі світним візерунком (ромби й смуги),
# вісім ламаних ніг зі світними колінами (коліна вище стегна — не гойдаються). Стегно 0.78, xMin 0.3.
hull, glow = bmesh.new(), bmesh.new()
blob(hull, F_PLUM, (0, 0.46, -0.2), (0.52, 0.36, 0.62), sub=2)
box(glow, G_MAGENTA, (0, 0.625, -0.2), (0.15, 0.04, 0.15), ry=0.785)
box(glow, G_MAGENTA, (0, 0.6, -0.01), (0.1, 0.04, 0.1), ry=0.785)
box(glow, G_MAGENTA, (0, 0.6, -0.39), (0.1, 0.04, 0.1), ry=0.785)
box(glow, G_CYAN, (0.14, 0.6, -0.2), (0.06, 0.04, 0.24))
box(glow, G_CYAN, (-0.14, 0.6, -0.2), (0.06, 0.04, 0.24))
spike(hull, F_NIGHT, (0, 0.44, -0.48), (0, 0.4, -0.6), 0.1, 0.1)
blob(hull, F_INDIGO, (0, 0.44, 0.24), (0.34, 0.24, 0.34))
box(hull, F_NIGHT, (0, 0.545, 0.24), (0.14, 0.04, 0.18))
def legs(sx):
    for z in (0.3, 0.12, -0.06, -0.24):
        hip = (0.15*sx, 0.46, z)
        knee = (0.46*sx, 0.8, z*1.5)
        mid = (0.66*sx, 0.25, z*1.9)
        frustum(hull, F_INDIGO, hip, knee, 0.06, 0.06, 0.05, 0.05)
        box(glow, G_CYAN, knee, (0.075, 0.075, 0.075))
        frustum(hull, F_TEALD, knee, mid, 0.05, 0.06, 0.04, 0.05)
        spike(hull, F_BLACK, mid, (0.76*sx, 0.0, z*2.1), 0.04, 0.04)
    frustum(hull, F_NIGHT, (0.07*sx, 0.42, 0.38), (0.08*sx, 0.38, 0.56), 0.1, 0.12, 0.06, 0.07)
    spike(hull, F_CREAM, (0.08*sx, 0.38, 0.56), (0.03*sx, 0.26, 0.68), 0.05, 0.05)
    box(glow, G_LIME, (0.085*sx, 0.52, 0.385), (0.09, 0.05, 0.03))
mirror(legs)
build('FSpider', hull, glow, offset_x=-6.0)
