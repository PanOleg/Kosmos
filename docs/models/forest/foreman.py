# Ліс, Прораб (бос) → Великий вовк: масивний чотирилапий звір заввишки ~3, світний гребінь
# уздовж хребта, кристали на плечах, світні очі й смуги на боках, ікла, пишний хвіст.
# Тулуб і хвіст вище 1.3; ноги нижче (стегно ~1.25).
hull, glow = bmesh.new(), bmesh.new()
def side(sx):
    # Передня лапа.
    frustum(hull, F_NIGHT, (0.62*sx, 1.8, 0.85), (0.72*sx, 0.95, 0.7), 0.5, 0.62, 0.32, 0.36)
    spike(hull, F_SLATE, (0.74*sx, 1.0, 0.54), (0.78*sx, 0.8, 0.26), 0.18, 0.2)
    frustum(hull, F_SLATE, (0.72*sx, 0.95, 0.7), (0.74*sx, 0.16, 0.86), 0.32, 0.36, 0.26, 0.28)
    box(hull, F_NIGHT, (0.74*sx, 0.1, 0.98), (0.44, 0.2, 0.56))
    for dx in (-0.14, 0.0, 0.14):
        spike(hull, F_CREAM, (0.74*sx + dx, 0.08, 1.24), (0.74*sx + dx, 0.0, 1.44), 0.09, 0.09)
    # Задня лапа: велике стегно, скакальний суглоб назад.
    frustum(hull, F_NIGHT, (0.55*sx, 1.75, -0.8), (0.68*sx, 0.9, -1.12), 0.46, 0.72, 0.28, 0.32)
    spike(hull, F_SLATE, (0.7*sx, 0.95, -1.26), (0.72*sx, 0.9, -1.56), 0.16, 0.2)
    frustum(hull, F_SLATE, (0.68*sx, 0.9, -1.12), (0.7*sx, 0.16, -0.92), 0.28, 0.32, 0.24, 0.26)
    box(hull, F_NIGHT, (0.7*sx, 0.1, -0.82), (0.4, 0.2, 0.52))
    for dx in (-0.1, 0.1):
        spike(hull, F_CREAM, (0.7*sx + dx, 0.08, -0.58), (0.7*sx + dx, 0.0, -0.42), 0.09, 0.09)
    # Вуха, брови, очі, щоки.
    spike(hull, F_NIGHT, (0.3*sx, 2.82, 1.6), (0.46*sx, 3.26, 1.46), 0.32, 0.14)
    spike(glow, G_MAGENTA, (0.3*sx, 2.84, 1.68), (0.43*sx, 3.14, 1.56), 0.16, 0.03)
    box(hull, F_NIGHT, (0.24*sx, 2.76, 2.02), (0.34, 0.08, 0.14), rz=-0.3*sx)
    box(glow, G_MAGENTA, (0.24*sx, 2.66, 2.06), (0.22, 0.09, 0.03), rz=-0.3*sx)
    spike(hull, F_PALE, (0.36*sx, 2.5, 1.62), (0.7*sx, 2.3, 1.36), 0.24, 0.3)
    spike(hull, F_PALE, (0.36*sx, 2.3, 1.5), (0.6*sx, 2.0, 1.3), 0.2, 0.24)
    # Ікла: верхнє велике й нижнє менше.
    spike(hull, F_CREAM, (0.14*sx, 2.3, 2.3), (0.15*sx, 1.98, 2.36), 0.09, 0.09)
    spike(hull, F_CREAM, (0.11*sx, 2.16, 2.22), (0.11*sx, 2.36, 2.26), 0.06, 0.06)
    spike(hull, F_CREAM, (0.17*sx, 2.3, 2.1), (0.17*sx, 2.14, 2.12), 0.06, 0.06)
    # Кристали на плечах.
    spike(glow, G_VIOLET, (0.66*sx, 2.3, 0.72), (1.45*sx, 2.9, 0.42), 0.3, 0.3)
    spike(glow, G_CYAN, (0.68*sx, 2.2, 0.36), (1.25*sx, 2.62, -0.1), 0.24, 0.24)
    spike(glow, G_VIOLET, (0.6*sx, 2.3, 1.0), (1.0*sx, 2.7, 0.92), 0.2, 0.2)
    # Смуги на боках.
    box(glow, G_CYAN, (0.69*sx, 2.0, 0.08), (0.05, 0.56, 0.1), rx=0.3)
    box(glow, G_CYAN, (0.6*sx, 1.92, -0.3), (0.05, 0.5, 0.1), rx=0.3)
    box(glow, G_CYAN, (0.55*sx, 1.88, -0.62), (0.05, 0.42, 0.1), rx=0.3)
mirror(side)
# Тулуб.
frustum(hull, F_SLATE, (0, 1.95, 0.1), (0, 2.02, 1.05), 1.3, 1.15, 1.45, 1.35)
frustum(hull, F_NIGHT, (0, 1.86, -1.05), (0, 1.95, 0.1), 0.95, 0.85, 1.25, 1.1)
frustum(hull, F_PALE, (0, 1.75, 1.0), (0, 1.42, 1.22), 0.9, 0.5, 0.4, 0.2)
# Шия й голова.
frustum(hull, F_SLATE, (0, 2.28, 0.95), (0, 2.56, 1.5), 1.0, 0.95, 0.72, 0.7)
box(hull, F_SLATE, (0, 2.56, 1.72), (0.84, 0.6, 0.66))
frustum(hull, F_PALE, (0, 2.5, 2.0), (0, 2.4, 2.42), 0.54, 0.36, 0.32, 0.22)
box(hull, F_BLACK, (0, 2.44, 2.44), (0.2, 0.12, 0.06))
frustum(hull, F_NIGHT, (0, 2.28, 1.9), (0, 2.08, 2.3), 0.38, 0.12, 0.24, 0.08)
box(glow, G_MAGENTA, (0, 2.19, 2.08), (0.2, 0.03, 0.3), rx=0.46)
box(glow, G_CYAN, (0, 2.855, 1.7), (0.14, 0.03, 0.3), ry=0.785)
frustum(glow, G_CYAN, (0, 2.67, 2.02), (0, 2.57, 2.36), 0.08, 0.03, 0.05, 0.03)
# Світний гребінь уздовж хребта (від потилиці до хвоста).
ridge = ((1.36, 2.82, 0.5), (1.0, 2.7, 0.56), (0.62, 2.58, 0.5), (0.24, 2.48, 0.42), (-0.14, 2.4, 0.36),
         (-0.5, 2.33, 0.3), (-0.84, 2.27, 0.26))
for k, (z, y, h) in enumerate(ridge):
    spike(glow, G_VIOLET if k % 2 else G_CYAN, (0, y - 0.04, z), (0, y + h, z - 0.22), 0.2, 0.4)
# Пасма гриви довкола шиї.
for sx in (1, -1):
    for z, y, o in ((1.3, 2.7, 0.5), (0.95, 2.6, 0.62), (0.6, 2.5, 0.66)):
        spike(hull, F_PALE, (o * 0.6 * sx, y, z), ((o + 0.3) * sx, y + 0.12, z - 0.4), 0.3, 0.26)
# Хвіст.
frustum(hull, F_NIGHT, (0, 2.1, -1.0), (0, 2.3, -1.36), 0.3, 0.3, 0.5, 0.44)
frustum(hull, F_SLATE, (0, 2.3, -1.36), (0, 2.16, -1.62), 0.5, 0.44, 0.34, 0.3)
spike(glow, G_VIOLET, (0, 2.16, -1.62), (0, 1.92, -1.84), 0.34, 0.3)
frustum(glow, G_CYAN, (0, 2.22, -1.2), (0, 2.27, -1.3), 0.44, 0.42, 0.5, 0.46)
build('FForeman', hull, glow, offset_x=-14.0)
