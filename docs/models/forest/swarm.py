# Ліс, Рій → Нічний метелик: крихітне тільце, трикутні крильця зі світними плямами, вусики.
hull, glow = bmesh.new(), bmesh.new()
frustum(hull, F_BARKL, (0, 0, -0.16), (0, 0.01, 0.1), 0.06, 0.06, 0.1, 0.09)
box(hull, F_PALE, (0, 0.02, 0.13), (0.1, 0.09, 0.08))
def side(sx):
    spike(hull, F_PLUM, (0.04*sx, 0.04, 0.04), (0.17*sx, 0.1, 0.1), 0.2, 0.012)
    spike(hull, F_INDIGO, (0.04*sx, 0.035, -0.1), (0.14*sx, 0.07, -0.27), 0.12, 0.012)
    spike(glow, G_CYAN, (0.07*sx, 0.07, 0.055), (0.155*sx, 0.105, 0.095), 0.09, 0.012)
    spike(glow, G_MAGENTA, (0.06*sx, 0.055, -0.13), (0.13*sx, 0.078, -0.25), 0.055, 0.012)
    spike(hull, F_PALE, (0.03*sx, 0.06, 0.16), (0.09*sx, 0.15, 0.26), 0.012, 0.012)
    box(glow, G_LIME, (0.045*sx, 0.04, 0.165), (0.03, 0.035, 0.035))
mirror(side)
build('FSwarm', hull, glow, offset_x=10.0)
