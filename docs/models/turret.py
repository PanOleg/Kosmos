# Турель (TURRET): тринога, поворотна основа, броньована голова з довгим стволом і червоним оком,
# ззаду світний блок живлення — слабке місце. Стоїть на підлозі.
hull, glow = bmesh.new(), bmesh.new()
for k in range(3):
    a = k / 3 * math.pi * 2 + math.pi / 2
    knee = (math.sin(a)*0.42, 0.42, math.cos(a)*0.42)
    frustum(hull, DARK, (0, 0.6, 0), knee, 0.09, 0.09, 0.08, 0.08)
    box(hull, MID, knee, (0.1, 0.1, 0.1))
    frustum(hull, MID, knee, (math.sin(a)*0.68, 0.03, math.cos(a)*0.68), 0.08, 0.08, 0.06, 0.06)
    box(hull, DARK, (math.sin(a)*0.7, 0.025, math.cos(a)*0.7), (0.14, 0.05, 0.14))
cyl(hull, MID, (0, 0.55, 0), (0, 0.75, 0), 0.34, n=10)
box(hull, PALE, (0, 0.97, 0), (0.62, 0.42, 0.7))
box(hull, MID, (0, 0.97, 0.36), (0.5, 0.3, 0.04))
box(hull, YELLOW, (0, 1.2, 0), (0.64, 0.05, 0.72))
box(hull, STRIPE, (0.2, 1.2, 0), (0.08, 0.055, 0.72))
box(hull, STRIPE, (-0.2, 1.2, 0), (0.08, 0.055, 0.72))
box(hull, RED, (0.32, 0.97, 0.1), (0.02, 0.12, 0.4))
box(hull, RED, (-0.32, 0.97, 0.1), (0.02, 0.12, 0.4))
cyl(hull, DARK, (0, 1.0, 0.36), (0, 1.0, 1.0), 0.12, 0.1, n=8)
cyl(hull, STEEL, (0, 1.0, 0.6), (0, 1.0, 0.72), 0.14, n=8)
box(hull, DARK, (0, 1.0, 1.02), (0.22, 0.22, 0.08))
box(hull, DARK, (0, 0.97, -0.4), (0.44, 0.3, 0.1))
box(glow, WHITE, (0, 0.97, -0.455), (0.34, 0.2, 0.02))
box(glow, WHITE, (0, 1.06, 0.385), (0.12, 0.06, 0.02))
build('Turret', hull, glow, offset_x=-10.5)
