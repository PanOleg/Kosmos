# Павук (SPIDER): світле броньоване черевце, голова з кількома червоними очима,
# шість тонких ламаних ніг (стегно темне, гомілка світла, гострий кінчик). Стоїть на підлозі.
hull, glow = bmesh.new(), bmesh.new()
blob(hull, PALE, (0, 0.48, -0.1), (0.55, 0.34, 0.62))
box(hull, DARK, (0, 0.62, -0.12), (0.2, 0.06, 0.4))
box(hull, RED, (0, 0.655, -0.12), (0.06, 0.02, 0.3))
blob(hull, MID, (0, 0.5, 0.28), (0.3, 0.24, 0.26))
box(hull, DARK, (0, 0.44, 0.4), (0.18, 0.08, 0.08))
def legs(sx):
    for z in (0.22, 0.0, -0.22):
        hip = (0.18*sx, 0.48, z)
        knee = (0.48*sx, 0.8, z*1.4)
        foot = (0.74*sx, 0.0, z*1.9)
        frustum(hull, DARK, hip, knee, 0.06, 0.06, 0.05, 0.05)
        box(hull, MID, knee, (0.07, 0.07, 0.07))
        frustum(hull, PALE, knee, (0.66*sx, 0.25, z*1.75), 0.05, 0.06, 0.04, 0.05)
        spike(hull, DARK, (0.66*sx, 0.25, z*1.75), foot, 0.04, 0.04)
    spike(hull, PALE, (0.08*sx, 0.42, 0.38), (0.06*sx, 0.3, 0.52), 0.04, 0.04)
mirror(legs)
for x, y in ((0.07, 0.56), (-0.07, 0.56), (0.12, 0.5), (-0.12, 0.5)):
    box(glow, WHITE, (x, y, 0.405), (0.045, 0.045, 0.02))
build('Spider', hull, glow, offset_x=-6.0)
