# Снайпер (SNIPER DRONE): тонкий корпус, дуже довгий ствол з дульним гальмом, оптика,
# стрілоподібні крила. Дрон: центр корпусу в початку координат.
hull, glow = bmesh.new(), bmesh.new()
frustum(hull, DARK, (0, 0, -0.3), (0, 0, 0.28), 0.2, 0.16, 0.24, 0.18)
box(hull, PALE, (0, 0.07, -0.04), (0.2, 0.06, 0.42))
box(hull, RED, (0, 0.105, -0.04), (0.05, 0.02, 0.3))
cyl(hull, MID, (0, -0.02, 0.28), (0, -0.02, 1.4), 0.03, n=6)
box(hull, DARK, (0, -0.02, 1.42), (0.08, 0.06, 0.1))
box(hull, STEEL, (0, 0.13, 0.12), (0.06, 0.06, 0.22))
cyl(hull, DARK, (0, 0.13, 0.23), (0, 0.13, 0.26), 0.035, n=6)
box(hull, DARK, (0, -0.12, 0.0), (0.06, 0.1, 0.12))
def wings(sx):
    spike(hull, MID, (0.1*sx, 0.03, 0.02), (0.55*sx, 0.06, -0.35), 0.025, 0.18)
    spike(hull, PALE, (0.1*sx, 0.03, -0.22), (0.32*sx, 0.05, -0.42), 0.02, 0.1)
mirror(wings)
box(glow, WHITE, (0, 0.02, 0.29), (0.08, 0.06, 0.03))
box(glow, WHITE, (0, 0.13, 0.27), (0.04, 0.04, 0.01))
box(glow, WHITE, (0, -0.02, 1.48), (0.05, 0.05, 0.02))
build('Sniper', hull, glow, offset_x=8.0)
