# Крига, Панцир → Мамонт: кошлате тіло на чотирьох ногах-стовпах, горб над лопатками,
# висока голова-купол, хобот, закручені бивні зі світними кінчиками. Ззаду — світне ядро
# в темному кільці й кристали на крупі (спина — слабке місце).
hull, glow = bmesh.new(), bmesh.new()
def side(sx):
    for z in (0.62, -0.62):
        post(hull, MAUVED, (0.5*sx, 1.4, z), (0.52*sx, 0.6, z + 0.02), 0.44, 0.5, 0.38, 0.42)
        post(hull, SLATE, (0.52*sx, 0.6, z + 0.02), (0.52*sx, 0.14, z + 0.02), 0.38, 0.42, 0.4, 0.46)
        box(hull, INK, (0.52*sx, 0.07, z + 0.04), (0.44, 0.14, 0.5))
        for k in (-1, 0, 1):
            box(hull, IVORY, (0.52*sx + k*0.13, 0.06, z + 0.3), (0.09, 0.1, 0.06))
    # Кошлаті пасма по боках (вище стегна, щоб не гойдались із ногами).
    for k in range(5):
        spike(hull, MAUVED if k % 2 else SLATE, (0.72*sx, 1.8, 0.7 - k*0.36), (0.88*sx, 1.2, 0.66 - k*0.36), 0.34, 0.2)
    box(hull, MAUVED, (0.6*sx, 2.08, 0.92), (0.12, 0.6, 0.56), ry=-0.6*sx)
    # Бивень: униз-убік, далі вперед і кінчиком угору-всередину.
    frustum(hull, IVORY, (0.26*sx, 1.75, 1.38), (0.58*sx, 1.31, 1.55), 0.16, 0.16, 0.14, 0.14)
    frustum(hull, IVORY, (0.58*sx, 1.31, 1.55), (0.84*sx, 1.38, 1.8), 0.14, 0.14, 0.1, 0.1)
    spike(glow, CYAN, (0.84*sx, 1.38, 1.8), (0.64*sx, 1.7, 1.96), 0.1, 0.1)
    box(glow, CYAN, (0.375*sx, 2.15, 1.32), (0.03, 0.1, 0.14))
mirror(side)
blob(hull, MAUVE, (0, 1.82, -0.05), (1.6, 1.3, 2.1), sub=2)
blob(hull, MAUVED, (0, 2.22, 0.4), (1.1, 0.7, 0.9))
box(hull, SLATE, (0, 2.45, -0.35), (0.3, 0.08, 0.8))
box(hull, MAUVE, (0, 2.05, 1.15), (0.74, 0.8, 0.6))
blob(hull, MAUVED, (0, 2.45, 1.1), (0.66, 0.46, 0.6))
frustum(hull, MAUVE, (0, 1.95, 1.4), (0, 1.4, 1.62), 0.32, 0.3, 0.26, 0.24)
frustum(hull, MAUVED, (0, 1.4, 1.62), (0, 0.8, 1.66), 0.26, 0.24, 0.2, 0.18)
frustum(hull, SLATE, (0, 0.8, 1.66), (0, 0.55, 1.84), 0.2, 0.18, 0.13, 0.12)
frustum(hull, MAUVED, (0, 1.45, -1.05), (0, 1.2, -1.18), 0.1, 0.1, 0.06, 0.06)
# Слабке місце.
cyl(hull, INK, (0, 1.8, -0.85), (0, 1.8, -1.12), 0.4, n=12)
cyl(glow, EBLUE, (0, 1.8, -1.12), (0, 1.8, -1.15), 0.3, n=12)
for x, z, h in ((0, -0.62, 0.36), (0.28, -0.5, 0.26), (-0.28, -0.5, 0.26)):
    icicle(hull, glow, (x, 2.22, z), (x*1.3, 2.3 + h, z - 0.16), 0.22)
build('IShell', hull, glow, offset_x=-3.0)
