# Крига, Турель → Морж на крижині: нерухомий, товсте тіло, вусата морда з бивнями,
# гармата на спині дулом на +Z, ззаду світний блок — слабке місце. Стоїть на підлозі.
hull, glow = bmesh.new(), bmesh.new()
post(hull, ICEB, (0, 0.32, 0), (0, 0, 0), 1.16, 1.5, 1.32, 1.7)
blob(hull, SLATE, (0, 0.64, -0.1), (1.0, 0.7, 1.3), sub=2)
blob(hull, FUR, (0, 0.7, 0.55), (0.52, 0.46, 0.46))
box(hull, FURD, (0, 0.62, 0.76), (0.4, 0.22, 0.16))
box(hull, INK, (0, 0.7, 0.85), (0.12, 0.07, 0.03))
def side(sx):
    spike(hull, IVORY, (0.11*sx, 0.56, 0.8), (0.13*sx, 0.2, 0.9), 0.09, 0.09)
    box(glow, CYAN, (0.14*sx, 0.83, 0.71), (0.06, 0.05, 0.05))
    box(hull, FURD, (0.47*sx, 0.36, 0.32), (0.32, 0.08, 0.5), ry=0.3*sx)
    box(hull, FURD, (0.2*sx, 0.36, -0.74), (0.26, 0.07, 0.36), ry=-0.3*sx)
    box(hull, NAVY, (0.36*sx, 0.84, -0.1), (0.1, 0.06, 0.7), rz=-0.6*sx)
    icicle(hull, glow, (0.48*sx, 0.3, -0.5), (0.56*sx, 0.72, -0.62), 0.2)
    spike(hull, ICE, (0.52*sx, 0.3, 0.62), (0.6*sx, 0.52, 0.72), 0.14, 0.14)
mirror(side)
# Гармата.
box(hull, NAVY, (0, 1.0, -0.15), (0.36, 0.2, 0.5))
cyl(hull, INK, (0, 1.08, -0.1), (0, 1.08, 0.95), 0.1, 0.085, n=8)
cyl(hull, STEEL, (0, 1.08, 0.5), (0, 1.08, 0.62), 0.125, n=8)
box(hull, INK, (0, 1.08, 0.97), (0.2, 0.2, 0.08))
box(glow, CYAN, (0, 1.08, 1.015), (0.12, 0.12, 0.02))
# Слабке місце ззаду.
box(hull, INK, (0, 0.66, -0.7), (0.52, 0.36, 0.14))
box(glow, EBLUE, (0, 0.66, -0.775), (0.4, 0.26, 0.02))
build('ITurret', hull, glow, offset_x=-10.5)
