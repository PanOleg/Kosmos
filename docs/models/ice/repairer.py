# Крига, Ремонтник → Полярний заєць: стоїть стовпчиком, довгі вуха з чорними кінчиками,
# великі ступні, ранець зі світним хрестом, у правій лапі пальник зі світним кристалом,
# у лівій — крижаний уламок.
hull, glow = bmesh.new(), bmesh.new()
def legs(sx):
    post(hull, FURD, (0.14*sx, 0.44, 0.0), (0.15*sx, 0.08, 0.03), 0.16, 0.2, 0.12, 0.14)
    box(hull, NAVY, (0.15*sx, 0.04, 0.12), (0.14, 0.08, 0.4))
    frustum(hull, FUR, (0.07*sx, 1.02, 0.06), (0.1*sx, 1.34, -0.04), 0.1, 0.05, 0.08, 0.04)
    spike(hull, INK, (0.1*sx, 1.34, -0.04), (0.11*sx, 1.44, -0.08), 0.08, 0.04)
    box(glow, AURORA, (0.085*sx, 0.97, 0.24), (0.05, 0.05, 0.04))
mirror(legs)
frustum(hull, FUR, (0, 0.4, -0.02), (0, 0.84, 0.05), 0.44, 0.38, 0.3, 0.28)
box(hull, SNOW, (0, 0.62, 0.19), (0.22, 0.36, 0.05), rx=-0.1)
blob(hull, SNOW, (0, 0.5, -0.27), (0.2, 0.2, 0.2))
blob(hull, FUR, (0, 0.95, 0.1), (0.3, 0.27, 0.32))
box(hull, SNOW, (0, 0.9, 0.26), (0.15, 0.1, 0.08))
box(hull, INK, (0, 0.93, 0.3), (0.05, 0.04, 0.02))
# Ранець.
box(hull, SLATE, (0, 0.74, -0.27), (0.32, 0.3, 0.2))
cyl(hull, STEEL, (0.1, 0.86, -0.3), (0.1, 1.06, -0.42), 0.03, n=6)
box(glow, AURORA, (0, 0.74, -0.375), (0.2, 0.06, 0.02))
box(glow, AURORA, (0, 0.74, -0.375), (0.06, 0.2, 0.02))
box(glow, AURORA, (0, 0.895, -0.27), (0.2, 0.02, 0.1))
# Права лапа з пальником.
frustum(hull, FURD, (0.19, 0.76, 0.06), (0.3, 0.62, 0.3), 0.08, 0.08)
cyl(hull, STEEL, (0.3, 0.62, 0.3), (0.3, 0.62, 0.48), 0.04, 0.03, n=6)
spike(glow, AURORA, (0.3, 0.62, 0.48), (0.3, 0.64, 0.62), 0.09, 0.09)
# Ліва — з крижаним уламком.
frustum(hull, FURD, (-0.19, 0.76, 0.06), (-0.33, 0.66, 0.28), 0.08, 0.08)
spike(hull, ICEB, (-0.35, 0.66, 0.31), (-0.37, 1.0, 0.36), 0.12, 0.12)
spike(hull, ICEB, (-0.35, 0.66, 0.31), (-0.35, 0.42, 0.3), 0.12, 0.12)
build('IRepairer', hull, glow, offset_x=-8.0)
