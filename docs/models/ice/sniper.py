# Крига, Снайпер → Альбатрос: дуже довгі прямі вузькі крила з темними кінцями (темна смуга
# крил суцільна через спину), біле тіло, довгий помаранчевий гачкуватий дзьоб-ствол зі
# світною рискою-прицілом. Дрон: центр у початку координат.
hull, glow = bmesh.new(), bmesh.new()
# Тіло: сигара — груди, спина, хвіст із темним кінцем.
frustum(hull, SNOW, (0, 0.0, -0.26), (0, 0.02, 0.2), 0.2, 0.24, 0.27, 0.34)
frustum(hull, SNOW, (0, 0.02, 0.2), (0, 0.07, 0.42), 0.27, 0.34, 0.17, 0.2)
frustum(hull, SNOW, (0, 0.0, -0.26), (0, 0.0, -0.46), 0.2, 0.24, 0.24, 0.05)
frustum(hull, INK, (0, 0.0, -0.46), (0, 0.0, -0.56), 0.24, 0.05, 0.18, 0.03)
# Кругла голова й дзьоб із гачком.
blob(hull, SNOW, (0, 0.11, 0.5), (0.2, 0.22, 0.24))
frustum(hull, BEAK, (0, 0.08, 0.58), (0, 0.05, 1.1), 0.1, 0.1, 0.065, 0.06)
box(hull, BEAK, (0, 0.04, 1.13), (0.085, 0.085, 0.09))
spike(hull, BEAK, (0, 0.01, 1.16), (0, -0.14, 1.2), 0.07, 0.07)
box(glow, CYAN, (0, 0.125, 0.86), (0.03, 0.02, 0.48))
box(glow, EBLUE, (0, 0.04, 1.18), (0.05, 0.05, 0.02))
def side(sx):
    # Крило: пряме й вузьке, ледь уперед до «зап'ястка», далі назад; довгий темний кінець.
    frustum(hull, NAVY, (0.0, 0.17, 0.06), (0.34*sx, 0.16, 0.13), 0.25, 0.05, 0.2, 0.04)
    frustum(hull, NAVY, (0.34*sx, 0.16, 0.13), (0.6*sx, 0.13, 0.1), 0.2, 0.04, 0.15, 0.03)
    spike(hull, INK, (0.6*sx, 0.13, 0.1), (0.83*sx, 0.1, -0.04), 0.15, 0.03)
    # Світла смужка вздовж передньої крайки.
    frustum(hull, ICE, (0.1*sx, 0.175, 0.2), (0.34*sx, 0.17, 0.235), 0.04, 0.035, 0.03, 0.03)
    # Підібгані лапи й око.
    spike(hull, BEAK, (0.06*sx, -0.11, -0.2), (0.07*sx, -0.22, -0.36), 0.05, 0.04)
    box(glow, CYAN, (0.095*sx, 0.13, 0.56), (0.02, 0.05, 0.06))
mirror(side)
build('ISniper', hull, glow, offset_x=8.0)
