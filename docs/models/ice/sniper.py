# Крига, Снайпер → Альбатрос: довгі вузькі ламані крила з темними кінцями, біла голова,
# дуже довгий дзьоб-ствол зі світною рискою-прицілом. Дрон: центр у початку координат.
hull, glow = bmesh.new(), bmesh.new()
frustum(hull, FURD, (0, 0, -0.3), (0, 0.02, 0.3), 0.16, 0.14, 0.24, 0.2)
frustum(hull, SLATE, (0, 0, -0.3), (0, -0.01, -0.6), 0.16, 0.06, 0.3, 0.02)
frustum(hull, FUR, (0, 0.02, 0.3), (0, 0.05, 0.54), 0.2, 0.17, 0.15, 0.14)
box(hull, SNOW, (0, 0.06, 0.6), (0.17, 0.15, 0.18))
box(hull, NAVY, (0, 0.14, 0.58), (0.1, 0.02, 0.14))
frustum(hull, BEAK, (0, 0.04, 0.68), (0, 0.02, 1.36), 0.09, 0.08, 0.055, 0.045)
spike(hull, INK, (0, 0.02, 1.36), (0, -0.06, 1.47), 0.06, 0.05)
box(glow, CYAN, (0, 0.075, 1.02), (0.03, 0.02, 0.6))
box(hull, NAVY, (0, 0.105, 0.0), (0.08, 0.03, 0.5))
def side(sx):
    frustum(hull, NAVY, (0.1*sx, 0.05, 0.1), (0.38*sx, 0.12, 0.16), 0.26, 0.03, 0.2, 0.03)
    frustum(hull, NAVY, (0.38*sx, 0.12, 0.16), (0.62*sx, 0.08, 0.0), 0.2, 0.03, 0.11, 0.02)
    spike(hull, INK, (0.62*sx, 0.08, 0.0), (0.72*sx, 0.05, -0.2), 0.11, 0.02)
    frustum(hull, SNOW, (0.1*sx, 0.065, 0.2), (0.38*sx, 0.135, 0.24), 0.05, 0.03)
    spike(hull, INK, (0.05*sx, -0.07, -0.1), (0.06*sx, -0.2, -0.22), 0.04, 0.04)
    box(glow, CYAN, (0.09*sx, 0.08, 0.63), (0.02, 0.05, 0.06))
mirror(side)
box(glow, EBLUE, (0, 0.02, 1.33), (0.07, 0.06, 0.04))
build('ISniper', hull, glow, offset_x=8.0)
