# Крига, Скаут → Песець: компактне тіло на коротких лапах, клиноподібна лисяча голова з
# гострою мордочкою, великі трикутні вуха з темними спинками, білі щоки, величезний пишний
# хвіст (майже як тіло) з ТЕМНИМ кінцем. Стоїть на підлозі, дивиться на +Z; черевце вище 0.38.
hull, glow = bmesh.new(), bmesh.new()
blob(hull, FOX, (0, 0.68, 0.08), (0.44, 0.5, 0.8), sub=2)
box(hull, FURD, (0, 0.905, 0.04), (0.14, 0.04, 0.4))
blob(hull, SNOW, (0, 0.66, 0.38), (0.3, 0.34, 0.26))
# Голова-клин: широка потилиця, гостра мордочка.
frustum(hull, FOX, (0, 0.97, 0.34), (0, 0.92, 0.66), 0.42, 0.32, 0.15, 0.13)
frustum(hull, FURD, (0, 0.92, 0.66), (0, 0.89, 0.85), 0.15, 0.13, 0.06, 0.05)
box(hull, INK, (0, 0.89, 0.86), (0.07, 0.06, 0.04))
# Хвіст: круглий у перетині, розширюється до величезної «китиці», кінець темний.
cyl(hull, FOX, (0, 0.72, -0.22), (0, 0.82, -0.5), 0.09, 0.22, n=6, cap=False)
cyl(hull, FOX, (0, 0.82, -0.5), (0, 0.87, -0.88), 0.22, 0.26, n=6, cap=False)
cyl(hull, NAVY, (0, 0.87, -0.88), (0, 0.84, -1.14), 0.26, 0.19, n=6, cap=False)
cyl(hull, INK, (0, 0.84, -1.14), (0, 0.78, -1.4), 0.19, 0.01, n=6, cap=False)
def side(sx):
    # Велике трикутне вухо: темна спинка, світла серединка спереду.
    spike(hull, NAVY, (0.13*sx, 1.08, 0.4), (0.21*sx, 1.45, 0.36), 0.22, 0.09)
    spike(hull, SNOW, (0.13*sx, 1.08, 0.465), (0.19*sx, 1.34, 0.43), 0.1, 0.03)
    # Щока-пучок і око.
    spike(hull, SNOW, (0.15*sx, 0.92, 0.46), (0.29*sx, 0.84, 0.4), 0.14, 0.12)
    box(glow, CYAN, (0.115*sx, 1.0, 0.6), (0.05, 0.05, 0.03))
    # Передня лапа.
    post(hull, FURD, (0.14*sx, 0.5, 0.3), (0.14*sx, 0.06, 0.33), 0.13, 0.15, 0.1, 0.11)
    box(hull, NAVY, (0.14*sx, 0.03, 0.36), (0.11, 0.06, 0.17))
    # Задня: стегно й гомілка.
    post(hull, FURD, (0.15*sx, 0.58, -0.14), (0.16*sx, 0.28, -0.26), 0.14, 0.22, 0.1, 0.11)
    post(hull, FURD, (0.16*sx, 0.28, -0.26), (0.16*sx, 0.05, -0.18), 0.09, 0.1, 0.08, 0.09)
    box(hull, NAVY, (0.16*sx, 0.03, -0.15), (0.11, 0.06, 0.17))
mirror(side)
build('IScout', hull, glow, offset_x=0.0)
