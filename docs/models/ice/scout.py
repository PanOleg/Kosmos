# Крига, Скаут → Песець: округле пухнасте тіло на коротких лапах, коротка мордочка,
# щоки-пучки, дуже пишний хвіст із білим кінцем. Стоїть на підлозі, дивиться на +Z.
hull, glow = bmesh.new(), bmesh.new()
blob(hull, FOX, (0, 0.67, -0.05), (0.46, 0.54, 0.98), sub=2)
box(hull, FURD, (0, 0.925, -0.08), (0.16, 0.05, 0.6))
blob(hull, SNOW, (0, 0.67, 0.36), (0.34, 0.36, 0.3))
box(hull, FOX, (0, 0.96, 0.56), (0.34, 0.27, 0.28))
box(hull, FURD, (0, 1.1, 0.54), (0.12, 0.03, 0.22))
frustum(hull, SNOW, (0, 0.91, 0.68), (0, 0.89, 0.88), 0.17, 0.14, 0.1, 0.08)
box(hull, INK, (0, 0.9, 0.89), (0.07, 0.05, 0.04))
# Хвіст: розширюється до пишної «китиці».
frustum(hull, FOX, (0, 0.72, -0.42), (0, 0.8, -0.62), 0.16, 0.16, 0.34, 0.32)
frustum(hull, FOX, (0, 0.8, -0.62), (0, 0.82, -0.9), 0.34, 0.32, 0.4, 0.36)
frustum(hull, SNOW, (0, 0.82, -0.9), (0, 0.8, -1.04), 0.4, 0.36, 0.26, 0.22)
spike(hull, SNOW, (0, 0.8, -1.04), (0, 0.76, -1.16), 0.26, 0.22)
def side(sx):
    spike(hull, FURD, (0.11*sx, 1.07, 0.54), (0.12*sx, 1.27, 0.48), 0.14, 0.07)
    spike(hull, SNOW, (0.15*sx, 0.9, 0.54), (0.26*sx, 0.84, 0.5), 0.14, 0.12)
    box(glow, CYAN, (0.09*sx, 0.99, 0.705), (0.06, 0.05, 0.02))
    # Передня лапа.
    post(hull, FURD, (0.14*sx, 0.5, 0.24), (0.14*sx, 0.06, 0.27), 0.13, 0.15, 0.1, 0.11)
    box(hull, NAVY, (0.14*sx, 0.03, 0.3), (0.11, 0.06, 0.17))
    # Задня: стегно й гомілка.
    post(hull, FURD, (0.15*sx, 0.58, -0.32), (0.16*sx, 0.28, -0.44), 0.14, 0.22, 0.1, 0.11)
    post(hull, FURD, (0.16*sx, 0.28, -0.44), (0.16*sx, 0.05, -0.36), 0.09, 0.1, 0.08, 0.09)
    box(hull, NAVY, (0.16*sx, 0.03, -0.33), (0.11, 0.06, 0.17))
mirror(side)
build('IScout', hull, glow, offset_x=0.0)
