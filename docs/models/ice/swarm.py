# Крига, Рій → Сніжна мошка: тільце-крижинка з двох клинів, прозорі крильця, шип на спині.
hull, glow = bmesh.new(), bmesh.new()
frustum(hull, TEAL, (0, 0, -0.04), (0, 0.01, 0.12), 0.09, 0.09, 0.13, 0.11)
spike(hull, NAVY, (0, 0, -0.04), (0, -0.02, -0.28), 0.09, 0.09)
spike(hull, NAVY, (0, 0.01, 0.12), (0, -0.01, 0.26), 0.06, 0.05)
spike(hull, ICE, (0, 0.04, -0.02), (0, 0.17, -0.12), 0.05, 0.05)
def side(sx):
    spike(hull, ICE, (0.04*sx, 0.05, 0.04), (0.17*sx, 0.09, -0.1), 0.1, 0.01)
    spike(hull, ICE, (0.04*sx, 0.04, -0.04), (0.13*sx, 0.06, -0.24), 0.08, 0.01)
    spike(hull, NAVY, (0.05*sx, -0.02, 0.06), (0.12*sx, -0.09, 0.12), 0.025, 0.025)
    spike(hull, NAVY, (0.05*sx, -0.02, -0.02), (0.12*sx, -0.09, -0.08), 0.025, 0.025)
    box(glow, CYAN, (0.055*sx, 0.045, 0.11), (0.035, 0.04, 0.04))
mirror(side)
build('ISwarm', hull, glow, offset_x=10.0)
