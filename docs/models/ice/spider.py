# Крига, Павук → Крижаний краб: низький широкий панцир із кристалами на спині, очі на стеблах,
# по чотири ноги в боки, дві великі клешні спереду. Стоїть на підлозі.
hull, glow = bmesh.new(), bmesh.new()
blob(hull, TEAL, (0, 0.42, -0.05), (0.84, 0.34, 0.66), sub=2)
box(hull, TEALD, (0, 0.36, -0.05), (0.86, 0.08, 0.5))
icicle(hull, glow, (0, 0.52, -0.08), (0, 0.82, -0.2), 0.2)
spike(hull, ICE, (0.2, 0.5, -0.16), (0.27, 0.7, -0.28), 0.14, 0.14)
spike(hull, ICE, (-0.2, 0.5, -0.02), (-0.27, 0.68, -0.08), 0.14, 0.14)
spike(hull, ICE, (0.14, 0.52, 0.08), (0.17, 0.66, 0.1), 0.1, 0.1)
spike(hull, ICE, (-0.12, 0.5, -0.24), (-0.14, 0.64, -0.34), 0.1, 0.1)
def legs(sx):
    for z in (0.14, -0.02, -0.18, -0.32):
        hip = (0.36*sx, 0.4, z)
        knee = (0.58*sx, 0.6, z*1.4)
        frustum(hull, NAVY, hip, knee, 0.07, 0.07, 0.06, 0.06)
        box(hull, ICEB, knee, (0.08, 0.08, 0.08))
        spike(hull, SLATE, knee, (0.76*sx, 0.0, z*1.8 - 0.02), 0.07, 0.06)
    frustum(hull, SLATE, (0.3*sx, 0.4, 0.2), (0.52*sx, 0.38, 0.42), 0.1, 0.1)
    box(hull, TEALD, (0.55*sx, 0.38, 0.5), (0.24, 0.18, 0.24), ry=-0.2*sx)
    spike(hull, NAVY, (0.62*sx, 0.4, 0.58), (0.52*sx, 0.42, 0.78), 0.11, 0.1)
    spike(hull, NAVY, (0.47*sx, 0.37, 0.58), (0.5*sx, 0.35, 0.74), 0.08, 0.08)
    frustum(hull, SLATE, (0.1*sx, 0.5, 0.2), (0.12*sx, 0.66, 0.3), 0.04, 0.04)
    box(glow, AURORA, (0.12*sx, 0.68, 0.31), (0.07, 0.07, 0.07))
mirror(legs)
build('ISpider', hull, glow, offset_x=-6.0)
