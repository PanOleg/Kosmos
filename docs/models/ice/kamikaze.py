# Крига, Камікадзе → Крижаний кажан: перетинчасті крила з фестонами, великі вуха, ікла,
# у спині вмерзле світне ядро в кільці кристалів. Дрон: центр у початку координат.
hull, glow = bmesh.new(), bmesh.new()
blob(hull, NAVY, (0, 0, -0.02), (0.32, 0.28, 0.56))
box(hull, TEALD, (0, 0.04, 0.3), (0.24, 0.2, 0.2))
spike(hull, TEALD, (0, 0.0, 0.38), (0, -0.03, 0.52), 0.14, 0.1)
spike(hull, NAVY, (0, 0, -0.26), (0, -0.04, -0.5), 0.12, 0.06)
# Ядро й кристали довкола.
blob(glow, VIOLET, (0, 0.11, -0.06), (0.24, 0.2, 0.28))
for x, z, tx, tz in ((0.11, -0.2, 0.15, -0.3), (-0.11, -0.2, -0.15, -0.3)):
    spike(hull, ICE, (x, 0.08, z), (tx, 0.25, tz), 0.09, 0.09)
box(glow, VIOLET, (0, -0.15, -0.04), (0.14, 0.03, 0.26))
def side(sx):
    spike(hull, TEALD, (0.08*sx, 0.13, 0.3), (0.15*sx, 0.32, 0.36), 0.1, 0.05)
    spike(hull, SNOW, (0.06*sx, -0.05, 0.38), (0.06*sx, -0.16, 0.42), 0.035, 0.035)
    # Перетинка трьома клинами й «пальці» поверх.
    frustum(hull, TEAL, (0.1*sx, 0.03, -0.04), (0.38*sx, 0.1, 0.0), 0.44, 0.03, 0.4, 0.03)
    frustum(hull, TEALD, (0.38*sx, 0.1, 0.0), (0.6*sx, 0.06, 0.04), 0.4, 0.03, 0.14, 0.02)
    for x, z in ((0.17, -0.2), (0.36, -0.17), (0.52, -0.06)):
        spike(hull, TEAL, (x*sx, 0.07, z), ((x + 0.05)*sx, 0.03, z - 0.2), 0.17, 0.02)
    frustum(hull, NAVY, (0.1*sx, 0.07, 0.16), (0.6*sx, 0.09, 0.12), 0.05, 0.05, 0.03, 0.03)
    frustum(hull, NAVY, (0.36*sx, 0.115, 0.14), (0.3*sx, 0.09, -0.26), 0.035, 0.03)
    frustum(hull, NAVY, (0.4*sx, 0.115, 0.14), (0.5*sx, 0.08, -0.2), 0.035, 0.03)
    spike(hull, ICE, (0.6*sx, 0.09, 0.12), (0.63*sx, 0.1, 0.28), 0.05, 0.05)
    box(glow, CYAN, (0.07*sx, 0.09, 0.405), (0.06, 0.05, 0.02))
mirror(side)
build('IKamikaze', hull, glow, offset_x=6.0)
