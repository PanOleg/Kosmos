# Крига, Оса → Полярна сова: широкі округлі крила з темними смугами, велика кругла голова
# з білим «лицем», хвіст-віяло, світний крижаний уламок у кігтях. Дрон: центр у початку координат.
hull, glow = bmesh.new(), bmesh.new()
frustum(hull, FUR, (0, 0, -0.28), (0, 0.02, 0.18), 0.2, 0.14, 0.3, 0.2)
blob(hull, FUR, (0, 0.035, 0.32), (0.38, 0.23, 0.32))
box(hull, SNOW, (0, 0.03, 0.455), (0.3, 0.16, 0.04))
spike(hull, BEAK, (0, 0.0, 0.47), (0, -0.06, 0.56), 0.06, 0.06)
frustum(hull, FURD, (0, 0.01, -0.28), (0, 0.01, -0.5), 0.16, 0.03, 0.38, 0.02)
box(hull, SNOW, (0, 0.012, -0.49), (0.36, 0.03, 0.05))
spike(glow, EBLUE, (0, -0.1, 0.0), (0, -0.12, 0.36), 0.07, 0.06)
def side(sx):
    frustum(hull, SLATE, (0.12*sx, 0.04, 0.0), (0.5*sx, 0.1, 0.02), 0.42, 0.03, 0.46, 0.03)
    frustum(hull, FURD, (0.5*sx, 0.1, 0.02), (0.8*sx, 0.06, -0.03), 0.46, 0.03, 0.36, 0.02)
    frustum(hull, SLATE, (0.8*sx, 0.06, -0.03), (0.93*sx, 0.04, -0.08), 0.36, 0.02, 0.16, 0.02)
    for k in range(3):
        spike(hull, SNOW, (0.3*sx + k*0.24*sx, 0.07, -0.2), (0.32*sx + k*0.25*sx, 0.05, -0.34 + k*0.03), 0.2, 0.02)
    box(hull, NAVY, (0.32*sx, 0.085, 0.0), (0.05, 0.02, 0.42))
    box(hull, NAVY, (0.62*sx, 0.095, -0.01), (0.05, 0.02, 0.38))
    spike(hull, INK, (0.07*sx, -0.06, 0.04), (0.07*sx, -0.13, 0.12), 0.04, 0.04)
    box(glow, CYAN, (0.085*sx, 0.06, 0.48), (0.09, 0.08, 0.02))
mirror(side)
build('IWasp', hull, glow, offset_x=4.0)
