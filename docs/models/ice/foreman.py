# Крига, Прораб (бос) → Шаблезубий тигр: масивні лопатки, смуги, величезні ікла, гребінь
# крижаних шипів уздовж хребта зі світними кінцями, крижані шипи на плечах. Висота ~3.
hull, glow = bmesh.new(), bmesh.new()
BC, BR = (0, 1.88, -0.1), (0.72, 0.56, 1.25)
SC, SR = (0, 2.0, 0.85), (0.85, 0.65, 0.65)
blob(hull, FUR, BC, (BR[0]*2, BR[1]*2, BR[2]*2), sub=2)
blob(hull, FURD, SC, (SR[0]*2, SR[1]*2, SR[2]*2), sub=2)
def stripe(C, R, z, th, ln):
    k = max(0.2, 1 - ((z - C[2]) / R[2]) ** 2) ** 0.5
    box(hull, NAVY, (R[0]*k*math.sin(th), C[1] + R[1]*k*math.cos(th), z), (ln*k, 0.1, 0.13), rz=-th)
for z in (-1.0, -0.72, -0.44, -0.16):
    for th in (0.75, -0.75):
        stripe(BC, BR, z, th, 0.62)
for z in (0.55, 0.85, 1.15):
    for th in (0.8, -0.8):
        stripe(SC, SR, z, th, 0.7)
# Голова.
box(hull, FUR, (0, 2.25, 1.75), (0.9, 0.78, 0.8))
box(hull, NAVY, (0, 2.645, 1.72), (0.12, 0.03, 0.56))
box(hull, SNOW, (0, 2.1, 2.25), (0.56, 0.36, 0.3))
box(hull, INK, (0, 2.24, 2.4), (0.2, 0.1, 0.06))
box(hull, NAVY, (0, 1.8, 2.1), (0.46, 0.12, 0.5))
box(glow, EBLUE, (0, 1.875, 2.14), (0.34, 0.03, 0.36))
spike(hull, SNOW, (0, 1.74, 1.95), (0, 1.45, 1.9), 0.3, 0.2)
# Гребінь на хребті.
for z, by, ty, tz, w in ((1.15, 2.45, 2.85, 1.0, 0.26), (0.75, 2.55, 3.08, 0.5, 0.36), (0.3, 2.45, 3.0, 0.0, 0.34),
                         (-0.15, 2.36, 2.88, -0.48, 0.32), (-0.6, 2.3, 2.72, -0.92, 0.28), (-1.0, 2.12, 2.44, -1.26, 0.22)):
    icicle(hull, glow, (0, by, z), (0, ty, tz), w)
# Хвіст із крижаним кінцем.
frustum(hull, FUR, (0, 1.95, -1.25), (0, 1.75, -1.6), 0.26, 0.26, 0.22, 0.22)
frustum(hull, FURD, (0, 1.75, -1.6), (0, 2.0, -1.82), 0.22, 0.22, 0.18, 0.18)
spike(glow, CYAN, (0, 2.0, -1.82), (0, 2.42, -1.78), 0.18, 0.18)
def side(sx):
    # Передня лапа.
    post(hull, FURD, (0.8*sx, 1.75, 0.9), (0.92*sx, 0.8, 1.0), 0.5, 0.62, 0.4, 0.46)
    post(hull, FUR, (0.92*sx, 0.8, 1.0), (0.95*sx, 0.18, 1.05), 0.4, 0.46, 0.36, 0.4)
    box(hull, NAVY, (0.95*sx, 0.1, 1.2), (0.52, 0.2, 0.7))
    # Задня.
    post(hull, FURD, (0.72*sx, 1.8, -0.85), (0.88*sx, 0.85, -1.1), 0.46, 0.8, 0.36, 0.42)
    post(hull, FUR, (0.88*sx, 0.85, -1.1), (0.9*sx, 0.18, -0.9), 0.36, 0.4, 0.32, 0.36)
    box(hull, NAVY, (0.9*sx, 0.1, -0.75), (0.48, 0.2, 0.64))
    for k in (-1, 0, 1):
        spike(hull, IVORY, (0.95*sx + k*0.16, 0.1, 1.52), (0.95*sx + k*0.17, 0.02, 1.72), 0.1, 0.1)
    # Крижані шипи на плечах.
    icicle(hull, glow, (0.68*sx, 2.3, 0.9), (1.42*sx, 2.88, 0.6), 0.36)
    icicle(hull, glow, (0.62*sx, 2.25, 0.45), (1.12*sx, 2.7, 0.08), 0.26)
    # Морда: ікла, очі, брови, вуха, бакенбарди.
    spike(hull, IVORY, (0.2*sx, 1.96, 2.3), (0.2*sx, 1.3, 2.42), 0.18, 0.18)
    box(glow, CYAN, (0.24*sx, 2.42, 2.16), (0.2, 0.1, 0.03))
    box(hull, NAVY, (0.25*sx, 2.52, 2.13), (0.32, 0.08, 0.1), rz=-0.3*sx)
    spike(hull, FURD, (0.32*sx, 2.6, 1.6), (0.36*sx, 2.95, 1.48), 0.26, 0.14)
    spike(hull, SNOW, (0.42*sx, 2.2, 1.7), (0.88*sx, 2.05, 1.42), 0.5, 0.34)
    spike(hull, ICE, (0.42*sx, 1.98, 1.75), (0.76*sx, 1.75, 1.55), 0.4, 0.26)
mirror(side)
build('IForeman', hull, glow, offset_x=-14.0)
