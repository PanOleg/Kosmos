# Крига, Стрілець → Пінгвін: стоїть стовпчиком, темно-синя спина, біле черево, помаранчеві
# дзьоб і лапи, ласти в боки, сніжкомет біля черева дулом на +Z.
hull, glow = bmesh.new(), bmesh.new()
cyl(hull, NAVY, (0, 0.2, 0), (0, 0.6, 0), 0.3, 0.4, n=8)
cyl(hull, NAVY, (0, 0.6, 0), (0, 1.0, 0), 0.4, 0.33, n=8, cap=False)
cyl(hull, SLATE, (0, 1.0, 0), (0, 1.2, 0.02), 0.33, 0.22, n=8)
frustum(hull, SNOW, (0, 0.28, 0.3), (0, 1.05, 0.24), 0.4, 0.2, 0.3, 0.16)
blob(hull, NAVY, (0, 1.27, 0.04), (0.42, 0.38, 0.44))
spike(hull, BEAK, (0, 1.24, 0.2), (0, 1.19, 0.5), 0.13, 0.1)
# Чубчик — два крижані пера назад.
spike(hull, ICE, (0.07, 1.42, 0.02), (0.13, 1.5, -0.22), 0.07, 0.05)
spike(hull, ICE, (-0.07, 1.42, 0.02), (-0.13, 1.5, -0.22), 0.07, 0.05)
spike(hull, NAVY, (0, 0.34, -0.28), (0, 0.24, -0.52), 0.2, 0.08)
# Сніжкомет.
cyl(hull, STEEL, (0, 0.62, 0.3), (0, 0.62, 0.72), 0.1, 0.09, n=8)
cyl(hull, SLATE, (0, 0.62, 0.64), (0, 0.62, 0.76), 0.125, n=8)
cyl(glow, CYAN, (0, 0.62, 0.76), (0, 0.62, 0.78), 0.085, n=8)
blob(hull, ICE, (0, 0.78, 0.44), (0.17, 0.17, 0.17))
def side(sx):
    post(hull, BEAK, (0.16*sx, 0.22, 0.02), (0.16*sx, 0.06, 0.04), 0.12, 0.12)
    box(hull, BEAK, (0.17*sx, 0.04, 0.14), (0.2, 0.08, 0.36))
    frustum(hull, NAVY, (0.36*sx, 1.02, 0.0), (0.53*sx, 0.5, -0.06), 0.24, 0.07, 0.13, 0.05)
    box(hull, SLATE, (0.2*sx, 0.66, 0.36), (0.14, 0.1, 0.12))
    box(hull, SNOW, (0.17*sx, 1.26, 0.12), (0.06, 0.14, 0.16))
    box(glow, CYAN, (0.11*sx, 1.33, 0.2), (0.05, 0.05, 0.05))
mirror(side)
build('IGunner', hull, glow, offset_x=2.0)
