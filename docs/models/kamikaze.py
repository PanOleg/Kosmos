# Камікадзе (KAMIKAZE): броньована «крапля» з гострим світлим лобовим щитом (у лоб невразливий),
# червона світна щілина спереду, короткі крильця, сопло ззаду. Дрон: центр у початку координат.
hull, glow = bmesh.new(), bmesh.new()
blob(hull, MID, (0, 0, -0.1), (0.48, 0.42, 0.72), sub=2)
spike(hull, PALE, (0, 0, 0.12), (0, -0.02, 0.6), 0.56, 0.42)
spike(hull, PALE, (0, 0.13, 0.05), (0, 0.04, 0.5), 0.3, 0.16)
box(hull, DARK, (0, 0.2, -0.12), (0.16, 0.08, 0.36))
cyl(hull, DARK, (0, 0, -0.42), (0, 0, -0.52), 0.13, 0.1, n=8)
def fins(sx):
    spike(hull, DARK, (0.2*sx, 0, -0.1), (0.52*sx, -0.08, -0.32), 0.04, 0.22)
    spike(hull, RED, (0.2*sx, 0.02, -0.06), (0.4*sx, 0.0, -0.18), 0.03, 0.08)
mirror(fins)
box(glow, WHITE, (0, -0.01, 0.44), (0.22, 0.06, 0.05))
box(glow, WHITE, (0, -0.16, 0.2), (0.3, 0.04, 0.04))
cyl(glow, WHITE, (0, 0, -0.52), (0, 0, -0.54), 0.08, n=8)
build('Kamikaze', hull, glow, offset_x=6.0)
