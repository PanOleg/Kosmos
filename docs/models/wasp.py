# Оса (WASP): гострий корпус-жало, дві пари тонких крил-лез, гармата знизу, двигун ззаду.
# Дрон: центр корпусу в початку координат (висоту польоту дає код).
hull, glow = bmesh.new(), bmesh.new()
spike(hull, PALE, (0, 0.02, -0.05), (0, -0.02, 0.62), 0.3, 0.2)
frustum(hull, MID, (0, 0.02, -0.05), (0, 0.02, -0.34), 0.3, 0.2, 0.22, 0.16)
box(hull, DARK, (0, 0.03, -0.42), (0.24, 0.2, 0.14))
cyl(hull, STEEL, (0, 0.03, -0.48), (0, 0.03, -0.55), 0.08, n=8)
box(hull, PALE, (0, 0.12, 0.05), (0.12, 0.06, 0.3), rx=-0.12)
box(hull, RED, (0, 0.155, 0.02), (0.04, 0.02, 0.2), rx=-0.12)
cyl(hull, DARK, (0, -0.14, -0.05), (0, -0.14, 0.42), 0.035, n=6)
box(hull, DARK, (0, -0.1, 0.0), (0.08, 0.08, 0.18))
def wings(sx):
    for z, l, a in ((0.05, 0.62, 0.3), (-0.22, 0.5, 0.45)):
        spike(hull, MID, (0.1*sx, 0.07, z), (0.1*sx + l*sx, 0.18, z - l*a), 0.03, 0.15)
        box(hull, RED, (0.1*sx + l*0.45*sx, 0.13, z - l*a*0.45), (0.06, 0.035, 0.06))
mirror(wings)
box(glow, WHITE, (0, 0.05, 0.46), (0.1, 0.05, 0.04))
box(glow, WHITE, (0.06, 0.05, 0.4), (0.04, 0.04, 0.04))
box(glow, WHITE, (-0.06, 0.05, 0.4), (0.04, 0.04, 0.04))
cyl(glow, WHITE, (0, 0.03, -0.55), (0, 0.03, -0.57), 0.06, n=8)
build('Wasp', hull, glow, offset_x=4.0)
