# Прораб (FOREMAN, міні-бос): будівельний мех на двох масивних ногах, дві жовті стріли-крани
# з чорно-жовтими смугами й гаками-кігтями, кабіна з помаранчевим вікном. Висота ~3.
hull, glow = bmesh.new(), bmesh.new()
def side(sx):
    frustum(hull, DARK, (0.42*sx, 1.0, 0), (0.5*sx, 0.55, 0.18), 0.36, 0.4)
    box(hull, YELLOW, (0.5*sx, 0.58, 0.32), (0.3, 0.3, 0.1))
    frustum(hull, PALE, (0.5*sx, 0.55, 0.18), (0.5*sx, 0.12, 0.0), 0.4, 0.46, 0.44, 0.5)
    box(hull, STRIPE, (0.73*sx, 0.34, 0.06), (0.03, 0.3, 0.3))
    box(hull, DARK, (0.5*sx, 0.07, 0.12), (0.52, 0.14, 0.8))
    # Стріла крана з плеча вгору-вперед, далі вниз — трос і гак-кіготь.
    box(hull, DARK, (0.72*sx, 1.85, -0.1), (0.36, 0.36, 0.42))
    frustum(hull, YELLOW, (0.75*sx, 1.9, -0.1), (0.95*sx, 2.9, 0.9), 0.24, 0.24, 0.2, 0.2)
    frustum(hull, YELLOW, (0.95*sx, 2.9, 0.9), (0.95*sx, 2.6, 1.9), 0.2, 0.2, 0.16, 0.16)
    for k in range(3):
        t = 0.2 + k * 0.27
        p = (0.75*sx + (0.2*sx)*t, 1.9 + 1.0*t, -0.1 + 1.0*t)
        frustum(hull, STRIPE, (p[0], p[1] - 0.05, p[2] - 0.05), (p[0], p[1] + 0.05, p[2] + 0.05), 0.26, 0.26)
    frustum(hull, STRIPE, (0.95*sx, 2.6, 1.9), (0.95*sx, 1.45, 1.95), 0.04, 0.04)
    box(hull, DARK, (0.95*sx, 1.38, 1.95), (0.3, 0.16, 0.22))
    spike(hull, STEEL, (1.06*sx, 1.32, 1.95), (1.08*sx, 1.05, 2.12), 0.06, 0.08)
    spike(hull, STEEL, (0.84*sx, 1.32, 1.95), (0.82*sx, 1.05, 2.12), 0.06, 0.08)
    box(glow, WHITE, (0.95*sx, 2.97, 0.9), (0.1, 0.06, 0.1))
mirror(side)
box(hull, PALE, (0, 1.2, 0), (1.3, 0.6, 1.2))
box(hull, YELLOW, (0, 1.65, -0.1), (1.24, 0.5, 1.1))
box(hull, STRIPE, (0, 1.4, 0.61), (1.26, 0.1, 0.03))
for k in range(5):
    box(hull, YELLOW, (-0.5 + k*0.25, 1.4, 0.625), (0.1, 0.1, 0.02))
box(hull, MID, (0, 2.1, 0.2), (0.9, 0.55, 0.75))
box(hull, DARK, (0, 2.4, 0.2), (0.96, 0.06, 0.8))
box(hull, DARK, (0, 1.55, -0.82), (1.1, 0.62, 0.36))
box(hull, RED, (0, 1.55, -1.005), (0.6, 0.08, 0.02))
cyl(hull, STEEL, (0, 2.43, 0), (0, 2.55, 0), 0.1, n=8)
box(glow, WHITE, (0, 2.12, 0.58), (0.62, 0.2, 0.02))
blob(glow, WHITE, (0, 2.62, 0), (0.16, 0.16, 0.16))
build('Foreman', hull, glow, offset_x=-14.0)
