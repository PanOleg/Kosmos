# Пустеля, Снайпер → Москіт: тонке тіло, дуже довгий хоботок-ствол, вузькі крила,
# звислі ламані лапки. Дрон: центр корпусу в початку координат.
hull, glow = bmesh.new(), bmesh.new()
frustum(hull, DARK, (0, 0, -0.1), (0, 0, 0.28), 0.16, 0.14, 0.2, 0.17)
frustum(hull, MID, (0, 0, -0.1), (0, -0.05, -0.62), 0.14, 0.12, 0.05, 0.05)
for k in range(3):
    box(hull, RED, (0, -0.012 - k*0.014, -0.22 - k*0.13), (0.13 - k*0.025, 0.11 - k*0.02, 0.03))
blob(hull, PALE, (0, 0.03, 0.35), (0.17, 0.15, 0.15))
cyl(hull, MID, (0, -0.02, 0.4), (0, -0.02, 1.4), 0.026, n=6)
box(hull, DARK, (0, -0.02, 1.42), (0.07, 0.06, 0.1))
def side(sx):
    frustum(hull, PALE, (0.08*sx, 0.09, 0.1), (0.62*sx, 0.15, -0.28), 0.17, 0.015, 0.08, 0.015)
    for z in (0.2, 0.02):
        frustum(hull, DARK, (0.08*sx, -0.05, z), (0.3*sx, 0.0, z + 0.14), 0.025, 0.025)
        frustum(hull, DARK, (0.3*sx, 0.0, z + 0.14), (0.36*sx, -0.26, z + 0.22), 0.02, 0.02)
    spike(hull, MID, (0.04*sx, 0.09, 0.4), (0.12*sx, 0.2, 0.58), 0.02, 0.02)
    box(glow, WHITE, (0.07*sx, 0.05, 0.4), (0.04, 0.05, 0.05))
mirror(side)
box(glow, WHITE, (0, -0.02, 1.48), (0.05, 0.05, 0.02))
build('DSniper', hull, glow, offset_x=8.0)
