# Пустеля, Оса → Гриф: розкинуті крила з «пір'ям» на кінцях, гачкуватий жовтий дзьоб,
# хвіст-віяло, гармата під черевом. Дрон: центр корпусу в початку координат.
hull, glow = bmesh.new(), bmesh.new()
frustum(hull, MID, (0, 0, -0.3), (0, 0.02, 0.2), 0.14, 0.12, 0.22, 0.17)
frustum(hull, PALE, (0, 0.02, 0.2), (0, 0.07, 0.42), 0.11, 0.1, 0.09, 0.09)
box(hull, RED, (0, 0.06, 0.24), (0.14, 0.05, 0.05))
spike(hull, YELLOW, (0, 0.06, 0.44), (0, -0.03, 0.62), 0.08, 0.07)
frustum(hull, DARK, (0, 0, -0.3), (0, 0, -0.52), 0.12, 0.03, 0.3, 0.02)
cyl(hull, DARK, (0, -0.11, 0.0), (0, -0.11, 0.4), 0.03, n=6)
box(hull, DARK, (0, -0.08, 0.0), (0.07, 0.07, 0.16))
def side(sx):
    frustum(hull, DARK, (0.1*sx, 0.04, -0.02), (0.45*sx, 0.11, -0.06), 0.36, 0.03, 0.32, 0.03)
    frustum(hull, MID, (0.45*sx, 0.11, -0.06), (0.8*sx, 0.07, -0.16), 0.32, 0.03, 0.14, 0.02)
    for k in range(3):
        spike(hull, PALE, (0.76*sx, 0.07, -0.08 - k*0.07), (0.98*sx, 0.05, -0.16 - k*0.1), 0.02, 0.06)
    box(hull, RED, (0.3*sx, 0.1, 0.1), (0.2, 0.02, 0.05))
    box(glow, WHITE, (0.05*sx, 0.09, 0.38), (0.03, 0.03, 0.04))
mirror(side)
box(glow, WHITE, (0, -0.11, 0.41), (0.05, 0.05, 0.02))
build('DWasp', hull, glow, offset_x=4.0)
