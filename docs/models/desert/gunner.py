hull, glow = bmesh.new(), bmesh.new()
cyl(hull, MID, (0, 0, 0), (0, 0.17, 0), 0.44, n=10)
cyl(hull, PALE, (0, 0.17, 0), (0, 0.32, 0), 0.33, n=10)
cyl(hull, DARK, (0, 0.16, 0), (0, 0.18, 0), 0.45, n=10)
frustum(hull, PALE, (0, 0.32, 0), (0, 0.85, 0.1), 0.22, 0.22, 0.19, 0.17)
frustum(hull, MID, (0, 0.78, 0.08), (0, 1.22, 0.15), 0.3, 0.09, 0.66, 0.09)
frustum(hull, MID, (0, 1.22, 0.15), (0, 1.42, 0.2), 0.66, 0.09, 0.32, 0.09)
frustum(hull, PALE, (0, 0.8, 0.14), (0, 1.3, 0.21), 0.16, 0.06, 0.18, 0.06)
for k in range(4):
    box(hull, YELLOW, (0, 0.88 + k*0.11, 0.185 + k*0.015), (0.14, 0.03, 0.03))
box(hull, PALE, (0, 1.38, 0.32), (0.22, 0.15, 0.3))
frustum(hull, MID, (0, 1.36, 0.46), (0, 1.33, 0.62), 0.2, 0.12, 0.12, 0.08)
cyl(hull, STEEL, (0, 1.33, 0.5), (0, 1.33, 0.78), 0.04, n=6)
box(glow, WHITE, (0, 1.33, 0.785), (0.06, 0.06, 0.02))
spike(hull, DARK, (0.36, 0.08, -0.14), (0.62, 0.34, -0.4), 0.09, 0.09)
box(hull, YELLOW, (0.5, 0.21, -0.28), (0.07, 0.07, 0.07))
def side(sx):
    box(hull, RED, (0.2*sx, 1.16, 0.1), (0.1, 0.16, 0.02))
    box(glow, WHITE, (0.085*sx, 1.43, 0.42), (0.05, 0.04, 0.05))
mirror(side)
build('DGunner', hull, glow, offset_x=2.0)
