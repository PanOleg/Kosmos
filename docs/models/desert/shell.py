# Пустеля, Панцир → Верблюд: високий в'ючний мех на чотирьох ногах, два горби, ракетні блоки
# в'юками по боках (по 4 світні труби), світне ядро в грудях і ззаду (спина — слабке місце).
hull, glow = bmesh.new(), bmesh.new()
def side(sx):
    for z in (0.58, -0.62):
        frustum(hull, DARK, (0.42*sx, 1.3, z), (0.44*sx, 0.7, z + 0.06), 0.3, 0.34, 0.22, 0.24)
        box(hull, MID, (0.44*sx, 0.72, z + 0.16), (0.24, 0.22, 0.1))
        frustum(hull, PALE, (0.44*sx, 0.7, z + 0.06), (0.44*sx, 0.12, z), 0.22, 0.24, 0.2, 0.22)
        box(hull, DARK, (0.44*sx, 0.06, z + 0.05), (0.34, 0.12, 0.44))
    # В'юк — ракетний блок.
    box(hull, MID, (0.82*sx, 1.8, -0.05), (0.52, 0.52, 0.72))
    box(hull, DARK, (0.82*sx, 1.8, 0.31), (0.46, 0.46, 0.06))
    box(hull, RED, (0.82*sx, 2.07, -0.05), (0.42, 0.03, 0.6))
    for r in range(2):
        for c in range(2):
            x, y = 0.82*sx + (c - 0.5)*0.2, 1.8 + (r - 0.5)*0.2
            cyl(hull, STEEL, (x, y, 0.3), (x, y, 0.36), 0.075, n=8)
            cyl(glow, WHITE, (x, y, 0.355), (x, y, 0.365), 0.052, n=8)
    spike(hull, PALE, (0.12*sx, 2.5, 1.2), (0.17*sx, 2.68, 1.14), 0.08, 0.05)
    box(glow, WHITE, (0.165*sx, 2.42, 1.4), (0.02, 0.06, 0.08))
mirror(side)
box(hull, DARK, (0, 1.28, 0), (0.9, 0.22, 1.6))
box(hull, PALE, (0, 1.62, 0), (1.12, 0.7, 1.9))
box(hull, RED, (0, 1.985, -0.05), (1.14, 0.04, 0.9))
blob(hull, MID, (0, 2.08, 0.38), (0.72, 0.62, 0.62))
blob(hull, MID, (0, 2.08, -0.42), (0.72, 0.62, 0.62))
box(hull, YELLOW, (0, 2.4, 0.38), (0.2, 0.05, 0.2))
box(hull, YELLOW, (0, 2.4, -0.42), (0.2, 0.05, 0.2))
frustum(hull, PALE, (0, 1.75, 0.85), (0, 2.34, 1.16), 0.42, 0.46, 0.3, 0.32)
box(hull, PALE, (0, 2.4, 1.32), (0.32, 0.3, 0.46))
frustum(hull, MID, (0, 2.36, 1.52), (0, 2.28, 1.78), 0.28, 0.24, 0.2, 0.16)
box(hull, DARK, (0, 2.25, 1.79), (0.18, 0.1, 0.04))
frustum(hull, DARK, (0, 1.75, -0.95), (0, 1.15, -1.14), 0.08, 0.08, 0.05, 0.05)
cyl(hull, DARK, (0, 1.6, 0.95), (0, 1.6, 0.99), 0.32, n=12)
cyl(hull, DARK, (0, 1.6, -0.95), (0, 1.6, -0.99), 0.3, n=12)
cyl(glow, WHITE, (0, 1.6, 0.99), (0, 1.6, 1.01), 0.24, n=12)
cyl(glow, WHITE, (0, 1.6, -0.99), (0, 1.6, -1.01), 0.22, n=12)
build('DShell', hull, glow, offset_x=-3.0)
