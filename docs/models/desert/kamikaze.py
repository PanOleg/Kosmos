# Пустеля, Камікадзе → Скарабей: опуклий панцир з розкритими надкрилами, світлий головний щит
# із рогом (у лоб невразливий), світне черевце. Дрон: центр у початку координат.
hull, glow = bmesh.new(), bmesh.new()
blob(hull, MID, (0, 0, -0.1), (0.5, 0.38, 0.68), sub=2)
box(hull, DARK, (0, 0.18, -0.12), (0.03, 0.04, 0.5))
box(hull, YELLOW, (0, 0.16, 0.12), (0.34, 0.05, 0.05))
spike(hull, PALE, (0, 0, 0.14), (0, -0.02, 0.52), 0.54, 0.34)
spike(hull, PALE, (0, 0.08, 0.28), (0, 0.32, 0.64), 0.11, 0.11)
cyl(hull, DARK, (0, 0, -0.42), (0, 0, -0.5), 0.12, 0.09, n=8)
def side(sx):
    spike(hull, DARK, (0.2*sx, 0.06, -0.08), (0.62*sx, 0.16, -0.34), 0.04, 0.34)
    spike(hull, RED, (0.2*sx, 0.08, -0.04), (0.44*sx, 0.13, -0.16), 0.03, 0.12)
    for z in (0.12, -0.06, -0.24):
        frustum(hull, DARK, (0.2*sx, -0.1, z), (0.34*sx, -0.2, z + 0.05), 0.04, 0.04)
mirror(side)
box(glow, WHITE, (0, -0.01, 0.4), (0.22, 0.06, 0.05))
box(glow, WHITE, (0, -0.18, 0.0), (0.26, 0.04, 0.3))
cyl(glow, WHITE, (0, 0, -0.5), (0, 0, -0.52), 0.08, n=8)
build('DKamikaze', hull, glow, offset_x=6.0)
