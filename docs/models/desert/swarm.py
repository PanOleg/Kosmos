# Пустеля, Рій → Сарана: крихітне тіло, стрибкові лапки колінами вгору, крильця, червоні жвала.
hull, glow = bmesh.new(), bmesh.new()
frustum(hull, DARK, (0, 0, -0.18), (0, 0.01, 0.1), 0.08, 0.08, 0.13, 0.11)
box(hull, MID, (0, 0.02, 0.14), (0.12, 0.11, 0.09))
def side(sx):
    spike(hull, PALE, (0.04*sx, 0.06, 0.02), (0.15*sx, 0.09, -0.28), 0.02, 0.1)
    frustum(hull, MID, (0.06*sx, 0.0, -0.05), (0.15*sx, 0.13, -0.2), 0.035, 0.045)
    spike(hull, DARK, (0.15*sx, 0.13, -0.2), (0.17*sx, -0.09, -0.27), 0.03, 0.03)
    spike(hull, RED, (0.035*sx, -0.01, 0.17), (0.02*sx, -0.05, 0.26), 0.03, 0.03)
    spike(hull, MID, (0.04*sx, 0.07, 0.16), (0.1*sx, 0.18, 0.26), 0.015, 0.015)
    box(glow, WHITE, (0.05*sx, 0.045, 0.17), (0.035, 0.04, 0.04))
mirror(side)
build('DSwarm', hull, glow, offset_x=10.0)
