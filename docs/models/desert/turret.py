# Пустеля, Турель → Черепаха: гранчастий панцир із жовто-чорною смугою, гармата на спині,
# голова з червоним оком, ззаду світний блок живлення — слабке місце. Стоїть на підлозі.
hull, glow = bmesh.new(), bmesh.new()
blob(hull, MID, (0, 0.48, 0), (1.3, 0.72, 1.45), sub=2)
box(hull, DARK, (0, 0.24, 0), (1.1, 0.14, 1.25))
box(hull, YELLOW, (0, 0.84, 0), (0.7, 0.04, 0.9))
box(hull, STRIPE, (0.22, 0.845, 0), (0.08, 0.045, 0.9))
box(hull, STRIPE, (-0.22, 0.845, 0), (0.08, 0.045, 0.9))
def side(sx):
    for z in (0.46, -0.46):
        box(hull, DARK, (0.52*sx, 0.14, z), (0.26, 0.28, 0.28))
        box(hull, PALE, (0.56*sx, 0.05, z + 0.06), (0.24, 0.1, 0.3))
    box(hull, RED, (0.6*sx, 0.5, 0), (0.03, 0.1, 0.6))
    box(glow, WHITE, (0.09*sx, 0.5, 1.0), (0.04, 0.05, 0.04))
mirror(side)
frustum(hull, PALE, (0, 0.4, 0.62), (0, 0.48, 0.98), 0.24, 0.2, 0.2, 0.18)
box(hull, DARK, (0, 0.42, 1.0), (0.14, 0.05, 0.04))
box(hull, PALE, (0, 1.0, -0.05), (0.5, 0.3, 0.6))
box(hull, MID, (0, 1.0, 0.26), (0.4, 0.22, 0.04))
cyl(hull, DARK, (0, 1.02, 0.26), (0, 1.02, 1.0), 0.11, 0.09, n=8)
cyl(hull, STEEL, (0, 1.02, 0.55), (0, 1.02, 0.67), 0.13, n=8)
box(hull, DARK, (0, 1.02, 1.02), (0.2, 0.2, 0.08))
box(glow, WHITE, (0, 1.1, 0.285), (0.12, 0.05, 0.02))
box(hull, DARK, (0, 0.5, -0.7), (0.46, 0.3, 0.1))
box(glow, WHITE, (0, 0.5, -0.755), (0.34, 0.2, 0.02))
spike(hull, MID, (0, 0.3, -0.72), (0, 0.2, -0.95), 0.1, 0.08)
build('DTurret', hull, glow, offset_x=-10.5)
