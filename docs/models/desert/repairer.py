# Пустеля, Ремонтник → Сурикат: стоїть стовпчиком, темна «маска» довкола очей, хвіст-опора,
# зварювальний пальник у правій лапі, синя пластина-щит у лівій.
hull, glow = bmesh.new(), bmesh.new()
def legs(sx):
    frustum(hull, DARK, (0.13*sx, 0.45, -0.02), (0.15*sx, 0.08, 0.04), 0.15, 0.17, 0.11, 0.12)
    box(hull, DARK, (0.15*sx, 0.04, 0.1), (0.13, 0.08, 0.3))
    box(hull, DARK, (0.1*sx, 1.27, 0.04), (0.07, 0.07, 0.05))
    box(hull, DARK, (0.075*sx, 1.16, 0.215), (0.08, 0.07, 0.04))
    box(glow, WHITE, (0.075*sx, 1.165, 0.24), (0.045, 0.04, 0.02))
mirror(legs)
frustum(hull, RUST, (0, 0.4, -0.02), (0, 1.0, 0.06), 0.42, 0.36, 0.3, 0.26)
box(hull, PALE, (0, 0.7, 0.19), (0.22, 0.42, 0.05), rx=-0.13)
box(hull, STEEL, (0, 0.78, -0.2), (0.26, 0.34, 0.12))
cyl(hull, STEEL, (0.08, 0.95, -0.22), (0.08, 1.18, -0.26), 0.035, n=6)
blob(hull, RUST, (0, 1.14, 0.1), (0.27, 0.25, 0.29))
frustum(hull, PALE, (0, 1.11, 0.2), (0, 1.08, 0.4), 0.15, 0.13, 0.07, 0.06)
box(hull, DARK, (0, 1.08, 0.41), (0.06, 0.05, 0.03))
frustum(hull, RUST, (0, 0.42, -0.16), (0, 0.12, -0.5), 0.11, 0.11, 0.07, 0.07)
spike(hull, DARK, (0, 0.12, -0.5), (0, 0.04, -0.68), 0.07, 0.07)
frustum(hull, RUST, (0.2, 0.9, 0.08), (0.27, 0.72, 0.36), 0.08, 0.08)
cyl(hull, STEEL, (0.27, 0.72, 0.36), (0.26, 0.71, 0.5), 0.04, 0.025, n=6)
box(glow, WHITE, (0.26, 0.71, 0.52), (0.05, 0.05, 0.05))
frustum(hull, RUST, (-0.2, 0.9, 0.08), (-0.34, 0.76, 0.3), 0.08, 0.08)
box(hull, BLUE, (-0.42, 0.76, 0.32), (0.06, 0.6, 0.5), ry=0.3)
box(hull, MID, (-0.455, 0.76, 0.31), (0.02, 0.64, 0.08), ry=0.3)
build('DRepairer', hull, glow, offset_x=-8.0)
