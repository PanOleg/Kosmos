# Пустеля, Скаут → Шакал: механічний хижак на чотирьох лапах, гострі вуха, довга морда
# з червоними іклами, хвіст. Стоїть на підлозі, дивиться на +Z.
hull, glow = bmesh.new(), bmesh.new()
frustum(hull, PALE, (0, 0.62, -0.42), (0, 0.66, 0.3), 0.26, 0.3, 0.32, 0.36)
box(hull, DARK, (0, 0.81, -0.05), (0.1, 0.05, 0.62))
box(hull, RED, (0, 0.84, -0.05), (0.04, 0.02, 0.5))
frustum(hull, MID, (0, 0.72, 0.26), (0, 0.92, 0.5), 0.22, 0.24, 0.17, 0.19)
box(hull, PALE, (0, 0.96, 0.6), (0.23, 0.19, 0.25))
frustum(hull, MID, (0, 0.93, 0.7), (0, 0.89, 0.97), 0.15, 0.12, 0.08, 0.07)
box(hull, DARK, (0, 0.88, 0.98), (0.08, 0.06, 0.04))
box(hull, DARK, (0, 0.85, 0.8), (0.1, 0.03, 0.26))
frustum(hull, MID, (0, 0.66, -0.42), (0, 0.52, -0.85), 0.1, 0.1, 0.06, 0.06)
spike(hull, DARK, (0, 0.52, -0.85), (0, 0.46, -1.02), 0.07, 0.07)
def side(sx):
    spike(hull, PALE, (0.08*sx, 1.04, 0.55), (0.12*sx, 1.32, 0.5), 0.09, 0.05)
    spike(hull, RED, (0.04*sx, 0.87, 0.9), (0.04*sx, 0.78, 0.92), 0.03, 0.03)
    # Передня лапа.
    frustum(hull, DARK, (0.15*sx, 0.6, 0.22), (0.16*sx, 0.32, 0.3), 0.11, 0.13, 0.08, 0.09)
    frustum(hull, PALE, (0.16*sx, 0.32, 0.3), (0.16*sx, 0.05, 0.26), 0.08, 0.09, 0.07, 0.08)
    box(hull, DARK, (0.16*sx, 0.03, 0.3), (0.1, 0.06, 0.17))
    # Задня: масивне стегно, коліно назад.
    frustum(hull, DARK, (0.15*sx, 0.64, -0.34), (0.17*sx, 0.34, -0.52), 0.13, 0.18, 0.09, 0.1)
    box(hull, MID, (0.19*sx, 0.6, -0.34), (0.06, 0.16, 0.2))
    frustum(hull, PALE, (0.17*sx, 0.34, -0.52), (0.17*sx, 0.05, -0.4), 0.08, 0.09, 0.07, 0.08)
    box(hull, DARK, (0.17*sx, 0.03, -0.36), (0.1, 0.06, 0.17))
    box(glow, WHITE, (0.09*sx, 0.99, 0.725), (0.05, 0.04, 0.02))
mirror(side)
build('DScout', hull, glow, offset_x=0.0)
