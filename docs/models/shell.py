# Панцир (SHELL): величезний мех. Ракетні блоки на плечах (по 4 світні труби), руки-гармати,
# світне ядро в грудях і на спині (спина — слабке місце ×3). Висота ~2.6, стоїть на підлозі.
hull, glow = bmesh.new(), bmesh.new()
def side(sx):
    frustum(hull, DARK, (0.45*sx, 1.2, 0), (0.55*sx, 0.62, 0.12), 0.38, 0.44, 0.34, 0.4)
    box(hull, MID, (0.56*sx, 0.66, 0.3), (0.3, 0.3, 0.12), rx=-0.2)
    frustum(hull, PALE, (0.55*sx, 0.62, 0.12), (0.55*sx, 0.14, -0.02), 0.42, 0.48, 0.46, 0.5)
    box(hull, RED, (0.79*sx, 0.4, 0.05), (0.03, 0.26, 0.2))
    box(hull, DARK, (0.55*sx, 0.07, 0.1), (0.52, 0.14, 0.76))
    for tz in (-0.14, 0.14):
        box(hull, MID, (0.55*sx + tz, 0.06, 0.52), (0.12, 0.08, 0.14))
    # Ракетний блок: коробка, рамка, 4 труби-сопла.
    box(hull, MID, (0.95*sx, 2.15, -0.05), (0.62, 0.62, 0.72))
    box(hull, DARK, (0.95*sx, 2.15, 0.31), (0.56, 0.56, 0.06))
    box(hull, RED, (0.95*sx, 2.47, -0.05), (0.5, 0.03, 0.6))
    for r in range(2):
        for c in range(2):
            x, y = 0.95*sx + (c - 0.5)*0.24, 2.15 + (r - 0.5)*0.24
            cyl(hull, STEEL, (x, y, 0.3), (x, y, 0.36), 0.085, n=8)
            cyl(glow, WHITE, (x, y, 0.355), (x, y, 0.365), 0.06, n=8)
    # Рука-гармата.
    box(hull, PALE, (0.92*sx, 1.85, 0), (0.42, 0.34, 0.5))
    frustum(hull, DARK, (1.05*sx, 1.72, 0), (1.1*sx, 1.22, 0.3), 0.3, 0.3)
    box(hull, PALE, (1.1*sx, 1.1, 0.42), (0.38, 0.38, 0.62))
    cyl(hull, DARK, (1.1*sx, 1.1, 0.72), (1.1*sx, 1.1, 0.92), 0.11, n=8)
    box(hull, RED, (1.3*sx, 1.1, 0.42), (0.02, 0.1, 0.5))
mirror(side)
box(hull, DARK, (0, 1.35, 0), (1.2, 0.5, 0.8))
box(hull, PALE, (0, 1.85, 0), (1.6, 0.8, 1.1))
box(hull, MID, (0, 1.85, 0.56), (1.2, 0.6, 0.04))
cyl(hull, DARK, (0, 1.85, 0.56), (0, 1.85, 0.6), 0.36, n=12)
cyl(hull, DARK, (0, 1.85, -0.56), (0, 1.85, -0.6), 0.32, n=12)
box(hull, MID, (0, 2.35, 0.05), (0.72, 0.32, 0.62))
box(hull, DARK, (0, 2.4, 0.38), (0.42, 0.12, 0.06))
for k in range(6):
    t = k * math.pi / 3
    box(hull, RED, (math.cos(t)*0.33, 1.85 + math.sin(t)*0.33, 0.61), (0.06, 0.06, 0.02))
cyl(glow, WHITE, (0, 1.85, 0.6), (0, 1.85, 0.62), 0.26, n=12)
cyl(glow, WHITE, (0, 1.85, -0.6), (0, 1.85, -0.62), 0.24, n=12)
box(glow, WHITE, (0, 2.4, 0.42), (0.24, 0.05, 0.02))
build('Shell', hull, glow, offset_x=-3.0)
