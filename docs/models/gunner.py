# Стрілець (concept enemies.jpg, SHOOTER): солдат у світлій броні, кругла голова з візором,
# важкий бластер обома руками біля правого плеча. Висота ~1.45, стоїть на підлозі.
hull, glow = bmesh.new(), bmesh.new()


def side(sx):
    # Ноги: стегно темне, наколінник, світла гомілка, масивний черевик.
    frustum(hull, DARK, (0.14*sx, 0.66, 0), (0.15*sx, 0.36, 0.06), 0.15, 0.16, 0.13, 0.14)
    box(hull, MID, (0.155*sx, 0.37, 0.12), (0.14, 0.14, 0.08), rx=-0.2)
    frustum(hull, PALE, (0.15*sx, 0.36, 0.06), (0.15*sx, 0.08, 0.0), 0.16, 0.18, 0.15, 0.16)
    box(hull, RED, (0.235*sx, 0.24, 0.03), (0.02, 0.14, 0.08))
    box(hull, DARK, (0.15*sx, 0.045, 0.05), (0.17, 0.09, 0.28))
    box(hull, MID, (0.15*sx, 0.06, 0.18), (0.15, 0.06, 0.06))
    # Наплічники: дві пластини, верхня світла з червоною смугою.
    box(hull, PALE, (0.33*sx, 1.12, 0), (0.22, 0.14, 0.3), rz=-0.18*sx)
    box(hull, MID, (0.35*sx, 1.03, 0), (0.2, 0.08, 0.26), rz=-0.25*sx)
    box(hull, RED, (0.43*sx, 1.11, 0), (0.02, 0.06, 0.26), rz=-0.18*sx)


mirror(side)
# Таз, живіт, груди з пластинами, рюкзак-батарея.
box(hull, MID, (0, 0.69, 0), (0.36, 0.14, 0.24))
box(hull, DARK, (0, 0.84, 0), (0.3, 0.2, 0.2))
frustum(hull, PALE, (0, 0.9, 0), (0, 1.16, 0), 0.4, 0.26, 0.5, 0.3)
box(hull, MID, (0, 1.04, 0.15), (0.32, 0.18, 0.05))
box(hull, RED, (0, 0.98, 0.18), (0.1, 0.04, 0.02))
box(hull, DARK, (0, 1.05, -0.2), (0.34, 0.32, 0.14))
for k in range(3):
    box(hull, STEEL, (-0.1 + k*0.1, 1.05, -0.28), (0.06, 0.24, 0.03))
# Шия й голова: гранчаста сфера, темний візор, «вушка» сенсорів.
cyl(hull, DARK, (0, 1.16, 0), (0, 1.22, 0.01), 0.07, n=6)
blob(hull, PALE, (0, 1.32, 0.02), (0.28, 0.27, 0.3))
box(hull, DARK, (0, 1.31, 0.12), (0.22, 0.08, 0.08))
box(hull, MID, (0.15, 1.33, 0), (0.04, 0.1, 0.1))
box(hull, MID, (-0.15, 1.33, 0), (0.04, 0.1, 0.1))
box(glow, WHITE, (0, 1.31, 0.165), (0.08, 0.045, 0.02))
# Бластер: корпус, ствол-циліндр, магазин, приціл; обидві руки на ньому.
box(hull, DARK, (0.14, 1.0, 0.32), (0.12, 0.16, 0.6))
box(hull, MID, (0.14, 1.09, 0.3), (0.07, 0.04, 0.34))
box(hull, STEEL, (0.14, 1.12, 0.2), (0.05, 0.06, 0.12))
box(hull, DARK, (0.14, 0.88, 0.24), (0.07, 0.14, 0.1), rx=0.2)
cyl(hull, STEEL, (0.14, 1.0, 0.6), (0.14, 1.0, 0.82), 0.045, n=6)
box(hull, RED, (0.205, 1.0, 0.36), (0.01, 0.05, 0.3))
box(glow, WHITE, (0.14, 1.0, 0.825), (0.06, 0.06, 0.02))
frustum(hull, DARK, (0.33, 1.08, 0), (0.3, 0.9, 0.12), 0.1, 0.1)
frustum(hull, PALE, (0.3, 0.9, 0.12), (0.17, 0.95, 0.2), 0.1, 0.1, 0.08, 0.08)
frustum(hull, DARK, (-0.33, 1.08, 0), (-0.2, 0.9, 0.22), 0.1, 0.1)
frustum(hull, PALE, (-0.2, 0.9, 0.22), (0.08, 0.97, 0.45), 0.1, 0.1, 0.08, 0.08)

