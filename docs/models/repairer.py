# Ремонтник (REPAIRER): згорблений іржавий робот, зварювальні руки (світний пальник праворуч),
# синя пластина-щит на лівій руці, кругла голова з оком. Стоїть на підлозі.
hull, glow = bmesh.new(), bmesh.new()
def legs(sx):
    frustum(hull, DARK, (0.16*sx, 0.6, -0.05), (0.18*sx, 0.3, 0.06), 0.16, 0.17)
    box(hull, MID, (0.18*sx, 0.31, 0.13), (0.14, 0.12, 0.06))
    frustum(hull, RUST, (0.18*sx, 0.32, 0.06), (0.18*sx, 0.07, 0.0), 0.17, 0.2, 0.19, 0.22)
    box(hull, DARK, (0.18*sx, 0.04, 0.04), (0.2, 0.08, 0.3))
    frustum(hull, DARK, (0.32*sx, 1.0, 0.1), (0.38*sx, 0.78, 0.36), 0.1, 0.1)
    box(hull, RUST, (0.34*sx, 1.04, 0.06), (0.2, 0.14, 0.24), rz=-0.2*sx)
mirror(legs)
box(hull, DARK, (0, 0.68, 0), (0.42, 0.18, 0.3))
box(hull, RUST, (0, 0.95, 0.06), (0.56, 0.42, 0.42), rx=0.45)
box(hull, MID, (0, 0.98, -0.14), (0.44, 0.3, 0.12), rx=0.45)
cyl(hull, STEEL, (0.14, 1.12, -0.2), (0.14, 1.32, -0.24), 0.04, n=6)
box(hull, RED, (0, 0.88, 0.27), (0.12, 0.05, 0.03), rx=0.45)
blob(hull, PALE, (0, 1.06, 0.34), (0.26, 0.24, 0.26))
box(hull, DARK, (0, 1.05, 0.45), (0.18, 0.07, 0.04))
# Права рука — зварювальний пальник; ліва — тримач щита.
frustum(hull, RUST, (0.38, 0.78, 0.36), (0.26, 0.72, 0.6), 0.08, 0.08)
cyl(hull, STEEL, (0.26, 0.72, 0.6), (0.25, 0.71, 0.68), 0.04, 0.025, n=6)
frustum(hull, RUST, (-0.38, 0.78, 0.36), (-0.45, 0.8, 0.42), 0.08, 0.08)
box(hull, BLUE, (-0.52, 0.8, 0.42), (0.06, 0.62, 0.52), ry=0.3)
box(hull, MID, (-0.555, 0.8, 0.41), (0.02, 0.66, 0.08), ry=0.3)
box(glow, WHITE, (0, 1.07, 0.47), (0.08, 0.05, 0.02))
box(glow, WHITE, (0.25, 0.71, 0.7), (0.05, 0.05, 0.05))
build('Repairer', hull, glow, offset_x=-8.0)
